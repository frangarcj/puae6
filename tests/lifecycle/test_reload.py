"""LIFE01: a second load in the same process is the same machine as a load in a clean process.

The guest (generated here, straight-line because the micro-ROM assembler has no branches) selects DF0 and reads the /TK0 line of
CIA-A after every one of a dozen outward steps, then steps the head 10 tracks inward and stays there. The words it logs give the
cylinder the head was on when the guest started: on track 0 every read says so. A session must start with the head on track 0
whatever the previous one did; a hard reset (p6_reset), like the real drive, does not move the head.
The step probe (P6_RELOAD=1) unloads the image and loads it again in the same process and prints the second run after "pass 2".
"""
from pathlib import Path
import re
import tempfile
import unittest

from tests.input.test_input import CTRL, FIXTURES, KEY_Q, LAMI, RAMI, line, sdr
from tests.step.test_step import TOOLS, builder, configure_trace_tree, run_probe

READS, STEPS_IN, GAP = 12, 10, 100        # 100 NOPs are 200 colour clocks, more than the drive's minimum step interval (140)
UNITS = 4
BOOT_STEP = 1                             # the first write to PRB after a reset takes /STEP 0 -> 1 with every drive selected: one step out
TK0_LOW = 0x10                            # CIA-A PRA bit 4: /TK0, active low, so the bit is clear on track 0


def rom_source():
    a = ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
         "; Generated by tests/lifecycle/test_reload.py: logs /TK0 after each outward step, then steps 10 tracks inward.",
         "entry:", "    MOVE.W #$2700,SR", "    LEA $400.W,A7",
         "    MOVE.B #3,$BFE201.L          ; CIA-A DDRA: OVL and the power LED are outputs, the drive status bits inputs",
         "    MOVE.B #2,$BFE001.L          ; overlay off",
         "    MOVE.B #$FF,$BFD300.L        ; CIA-B DDRB: all outputs (drive control)",
         "    MOVE.B #$FF,$BFD100.L        ; PRB: nothing selected, motor off, side 0, direction out, /STEP high",
         "    LEA $1000.W,A0               ; log pointer",
         "    MOVE.B #$7F,$BFD100.L        ; motor on",
         "    MOVE.B #$77,$BFD100.L        ; select DF0",
         "    .nops %d" % GAP]
    for _ in range(READS):
        a += ["    MOVEQ #0,D2", "    MOVE.B $BFE001.L,D2          ; PRA", "    MOVE.W D2,(A0)+",
              "    MOVE.B #$76,$BFD100.L        ; /STEP 1 -> 0, direction out",
              "    MOVE.B #$77,$BFD100.L        ; /STEP 0 -> 1: one step towards track 0", "    .nops %d" % GAP]
    for _ in range(STEPS_IN):
        a += ["    MOVE.B #$74,$BFD100.L        ; /STEP 1 -> 0, direction in",
              "    MOVE.B #$75,$BFD100.L        ; /STEP 0 -> 1: one step away from track 0", "    .nops %d" % GAP]
    a += ["loop:", "    BRA.S loop"]
    return "\n".join(a) + "\n"


def run(exe, rom, env=None, seed=1):
    env = {"P6_DUMP_LOG": "1", **(env or {})}
    code, out = run_probe(exe, rom, UNITS, "steps", seed, timeout=600, extra=["pal"], env=env)
    assert code == 0, out[-600:]
    return out


def logged(text, unit):
    return [int(w, 16) for w in re.search(r"^logu %d:(.*)$" % unit, text, re.M)[1].split()]


def on_track_0(words):
    """One flag per read: was /TK0 asserted (the head on track 0) when the guest looked?"""
    return [not word & TK0_LOW for word in words[:READS]]


def passes(text):
    """The output of every load of a P6_RELOAD run, without its "pass K" line."""
    parts = re.split(r"^pass \d+\n", text, flags=re.M)
    return parts[1:]


@unittest.skipUnless(TOOLS, "toolchain unavailable")
class ReloadTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.exe = configure_trace_tree()
        cls.tmp = tempfile.TemporaryDirectory(prefix="p6-reload-")
        cls.rom = Path(cls.tmp.name) / "recalibrate.rom"
        cls.rom.write_bytes(builder.build(rom_source()))

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_a_clean_process_starts_with_the_head_on_track_0_and_the_guest_leaves_it_on_track_10(self):
        clean = run(self.exe, self.rom)
        self.assertEqual(on_track_0(logged(clean, 1)), [True] * READS)
        self.assertEqual(len(logged(clean, 1)), READS)

    def test_every_later_load_in_a_process_is_the_machine_of_a_clean_process(self):
        clean = run(self.exe, self.rom)
        loads = passes(run(self.exe, self.rom, {"P6_RELOAD": "3"}))
        self.assertEqual(len(loads), 3)
        for number, text in enumerate(loads, 1):
            self.assertEqual(on_track_0(logged(text, 1)), [True] * READS, f"load {number} began with the head where a session left it")
            self.assertEqual(text, clean, f"load {number} differs from a clean process")       # unit for unit, digests included

    def test_a_reset_inside_a_session_does_not_leak_into_the_next_load(self):
        loads = passes(run(self.exe, self.rom, {"P6_RELOAD": "2", "P6_RESET_AT": "3"}))
        self.assertEqual(loads[0], loads[1])                           # the second load repeats the first, reset included

    def test_a_hard_reset_does_not_move_the_head_but_a_load_does_start_over(self):
        text = run(self.exe, self.rom, {"P6_RESET_AT": "3"})
        self.assertEqual(on_track_0(logged(text, 1)), [True] * READS)
        after = on_track_0(logged(text, 3))                            # the reset restarted the guest, the drive kept its head
        self.assertEqual(after, [False] * (STEPS_IN - BOOT_STEP) + [True] * (READS - STEPS_IN + BOOT_STEP))

@unittest.skipUnless(TOOLS, "toolchain unavailable")
class ReloadKeyboardTests(unittest.TestCase):
    """The keys of the engine and its reset-chord state belong to a session too."""

    @classmethod
    def setUpClass(cls):
        cls.exe = configure_trace_tree()
        cls.tmp = tempfile.TemporaryDirectory(prefix="p6-reload-keys-")
        cls.rom = Path(cls.tmp.name) / "input_all.rom"
        cls.rom.write_bytes(builder.build((FIXTURES / "input_all.s").read_text(encoding="utf-8")))

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def execute(self, keys, extra=None):
        """Six units; `keys` are held from unit 3 to the end, so they are still held when the session ends."""
        script = Path(self.tmp.name) / "script.txt"
        script.write_text("\n".join(line(keys=keys if unit >= 3 else []) for unit in range(1, 7)) + "\n")
        env = {"P6_DUMP_LOG": "1", "P6_INPUT_SCRIPT": str(script), **(extra or {})}
        code, out = run_probe(self.exe, self.rom, 6, "steps", 1, timeout=600, extra=["pal"], env=env)
        self.assertEqual(code, 0, out[-600:])
        return out

    def test_keys_held_when_a_session_ends_are_pressed_again_in_the_next_load(self):
        clean = self.execute([KEY_Q, CTRL])
        logs = re.findall(r"^logu \d+:.*$", clean, re.M)
        self.assertIn(" %04x" % sdr(CTRL, True), " ".join(logs))                       # the script does press Ctrl
        for number, text in enumerate(passes(self.execute([KEY_Q, CTRL], {"P6_RELOAD": "3"})), 1):
            self.assertEqual(text, clean, f"load {number} differs from a clean process")

    def test_a_reset_chord_held_when_a_session_ends_does_not_fire_in_the_next_load(self):
        chord = [CTRL, LAMI, RAMI]
        clean = self.execute(chord)
        for number, text in enumerate(passes(self.execute(chord, {"P6_RELOAD": "2"})), 1):
            self.assertEqual(text, clean, f"load {number} differs from a clean process")

    def test_the_first_unit_of_a_keyboard_guest_is_identical_after_a_reload(self):
        # T13c: the keyboard interrupts of unit 1 used to come 8 to 11 colour clocks later after a reload, because cia_cycle_accurate
        # (worked out at the end of every frame, false in a process that has not finished one) kept the last session's value. The
        # stack of the guest then held another PC ($F80118 instead of $F80116). The digest of unit 1 is compared whole.
        clean = self.execute([KEY_Q, CTRL])
        self.assertEqual(passes(self.execute([KEY_Q, CTRL], {"P6_RELOAD": "2"}))[1], clean)

@unittest.skipUnless(TOOLS, "toolchain unavailable")
class ReloadFixtureTests(unittest.TestCase):
    """Every micro-ROM, the ones that drive the keyboard included (T13c): three loads in a process, each a clean process, digests included."""

    FIXTURES = {"boot": None, "copper_irq": {"HP": "2"}, "halt": None, "input_all": None, "input_rotate": None, "lof_stuck": None,
                "long_frame": None, "long_ops": {"PAD": "3"}, "stop": None, "vsync": None}

    def test_the_micro_roms_reload_as_a_clean_process(self):
        exe = configure_trace_tree()
        with tempfile.TemporaryDirectory(prefix="p6-reload-fixtures-") as directory:
            for name, defines in self.FIXTURES.items():
                rom = Path(directory) / f"{name}.rom"
                source = (FIXTURES / f"{name}.s").read_text(encoding="utf-8")
                rom.write_bytes(builder.build(source, defines) if defines else builder.build(source))
                with self.subTest(rom=name):
                    code, clean = run_probe(exe, rom, UNITS, "steps", 1, timeout=600, extra=["pal"], env={"P6_DUMP_LOG": "1"})
                    self.assertEqual(code, 0, clean[-400:])
                    code, text = run_probe(exe, rom, UNITS, "steps", 1, timeout=600, extra=["pal"],
                                           env={"P6_DUMP_LOG": "1", "P6_RELOAD": "3"})
                    self.assertEqual(code, 0, text[-400:])
                    loads = passes(text)
                    self.assertEqual(len(loads), 3)
                    for number, load in enumerate(loads, 1):
                        self.assertEqual(load, clean, f"{name}: load {number} differs from a clean process")

def clock_rom_source():
    """Logs the seconds digit of the MSM6242B clock eight times, then spins. The clock keeps time through a reset and a load starts it again."""
    a = ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
         "; Generated by tests/lifecycle/test_reload.py: reads the clock of the A500 and logs it.",
         "entry:", "    MOVE.W #$2700,SR", "    LEA $400.W,A7", "    MOVE.B #3,$BFE201.L", "    MOVE.B #2,$BFE001.L",
         "    LEA $1000.W,A0"]
    for _ in range(8):
        a += ["    MOVEQ #0,D2", "    MOVE.B $DC0001.L,D2          ; clock: seconds, units digit", "    MOVE.W D2,(A0)+", "    .nops 50"]
    a += ["loop:", "    MOVE.B $DC0001.L,D2          ; keeps reading the clock: a stale anchor is found by the next read", "    ADDQ.L #1,D0",
          "    BRA.S loop"]
    return "\n".join(a) + "\n"


@unittest.skipUnless(TOOLS, "toolchain unavailable")
class ReloadClockTests(unittest.TestCase):
    """The emulated clock is anchored to the engine's cycle counter, which starts over at every reset and every load."""

    @classmethod
    def setUpClass(cls):
        cls.exe = configure_trace_tree()
        cls.tmp = tempfile.TemporaryDirectory(prefix="p6-reload-clock-")
        cls.rom = Path(cls.tmp.name) / "clock.rom"
        cls.rom.write_bytes(builder.build(clock_rom_source()))

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def execute(self, env=None):
        return run(self.exe, self.rom, env)

    def test_the_guest_reads_the_clock(self):
        words = logged(self.execute(), 1)
        self.assertEqual(len(words), 8)                                # eight reads, all of a valid digit
        self.assertTrue(all(word <= 9 for word in words), words)

    def test_reading_the_clock_after_a_reset_does_not_fault_the_image(self):
        text = self.execute({"P6_RESET_AT": "3"})                      # run() asserts that every p6_run_frame succeeded
        self.assertEqual(len(logged(text, 3)), 8)                      # the guest started over and read the clock again

    def chord_run(self, held_units, units=40):
        """`units` units with Ctrl-Amiga-Amiga held in the given units: the keyboard reset, which no p6_reset asked for."""
        script = Path(self.tmp.name) / "chord.txt"
        script.write_text("\n".join(line(keys=[CTRL, LAMI, RAMI] if unit in held_units else []) for unit in range(1, units + 1)) + "\n")
        code, out = run_probe(self.exe, self.rom, units, "steps", 1, timeout=600, extra=["pal"], env={"P6_INPUT_SCRIPT": str(script)})
        self.assertEqual(code, 0, out[-400:])
        cycles = {int(m[1]): int(m[2]) for m in re.finditer(r"^unit (\d+) .* cycles=(\d+) ", out, re.M)}
        return cycles, int(re.search(r"final digest=\w+ ticks=(\d+)", out)[1])

    def test_reading_the_clock_after_a_keyboard_reset_does_not_fault_the_image(self):
        # The chord restarts the engine's cycle counter by a path no p6_reset took; the clock must follow it all the same.
        cycles, _ = self.chord_run(set(range(3, 7)))
        restarts = [unit for unit in range(2, 41) if cycles[unit] < cycles[unit - 1]]
        self.assertEqual(len(restarts), 1, cycles)                     # the machine did start over, once

    def test_the_callers_ticks_count_what_ran_before_a_keyboard_reset_restarted_the_counter(self):
        cycles, ticks = self.chord_run(set(range(3, 7)))
        restart = next(unit for unit in range(2, 41) if cycles[unit] < cycles[unit - 1])
        boundaries = cycles[restart - 1] + cycles[40]                 # what the boundary readings alone account for
        self.assertGreater(ticks, boundaries)                          # the chord's reset took effect 4 colour clocks into the unit
        self.assertLess(ticks - boundaries, cycles[restart - 1] - cycles[restart - 2], "at most the part of one unit before the restart")

    def test_a_reload_reads_the_clock_like_a_clean_process(self):
        clean = self.execute()
        for number, text in enumerate(passes(self.execute({"P6_RELOAD": "3"})), 1):
            self.assertEqual(text, clean, f"load {number} differs from a clean process")

if __name__ == "__main__":
    unittest.main()
