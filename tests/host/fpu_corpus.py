def transcendental_cases():
    cases = []
    for op, (opmode, name, inputs) in TRANSCENDENTAL.items():
        for value in inputs:
            x = X(Fraction(value).limit_denominator(10 ** 12) if isinstance(value, float) else Fraction(value))
            true = r.transcendental(name, r.value(x))
            code = prologue(0) + arm(0) + [a.cpgen_mem(op, a.EXTENDED, ext_imm(x), 0)] + finish_ext()
            ext, _ = r.round_value(true, 0)
            cases.append(Case(f"{op}-{label(x)}", code, record(ext, r.cc_of(ext)), close=(true, 4 if abs(value) < 100 else 32, None)))     # argument reduction loses bits with |x|
    for op, x, result, exceptions in EXACT:
        opmode = TRANSCENDENTAL[op][0] if op in TRANSCENDENTAL else a.OPMODE[op]
        code = prologue(0) + arm(0) + [a.cpgen_mem(opmode, a.EXTENDED, ext_imm(x), 0)] + finish_ext()
        # the exception bits of a transcendental function are not fixed by the manual when the result is exact (ln 1 sets INEX2): the condition codes are
        cases.append(Case(f"exact-{op}-{label(x)}", code, record(result, r.cc_of(result) | exceptions | r.accrued(exceptions)),
                          b"\xff" * 12 + (b"\xff\xff\xff\xff" if exceptions else b"\x0f\x00\x00\x00")))
    return cases


def long_words(*values):
    return b"".join((v & 0xFFFFFFFF).to_bytes(4, "big") for v in values)


def fsincos_cases():
    cases = []
    for value in (0.5, 1, -2, 3, 100, 0.001):
        x = X(Fraction(value).limit_denominator(10 ** 12))
        true_sin, true_cos = r.transcendental("sin", r.value(x)), r.transcendental("cos", r.value(x))
        sin, _ = r.round_value(true_sin, 0)
        cos, _ = r.round_value(true_cos, 0)
        # FSINCOS.X #x,FP2:FP1: the cosine goes to FP2, the sine to FP1
        code = prologue(0) + arm(0) + [a.cpgen_mem(a.FSINCOS + 2, a.EXTENDED, ext_imm(x), 1), a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), a.fmove_out(a.EXTENDED, 1, a.ind(0)),
                                       a.fmove_out(a.EXTENDED, 2, a.disp16(0, 16)), "    .word $41E8,$0020           ; LEA 32(A0),A0"]
        mask = b"\xff" * 12 + b"\x0f\x00\x00\x00" + b"\xff" * 12 + bytes(4)
        units = 4 if abs(value) < 100 else 32
        cases.append(Case(f"fsincos-{label(x)}", code, record(sin, r.cc_of(sin)) + record(cos, 0), mask, close=[(0, true_sin, units, None), (16, true_cos, units, None)], records=2))
    return cases


def control_cases():
    cases = []
    for name, regs, mask in (("fpcr", a.FPCR, 0xFFF0), ("fpsr", a.FPSR, 0x0FFFFFF8), ("fpiar", a.FPIAR, 0xFFFFFFFF)):
        for value in (0xFFFFFFFF, 0x000000A0, 0x00000400, 0x12345678):
            code = [a.fmove_ctrl_in(a.FPCR, a.imm_long(0)), a.fmove_ctrl_in(regs, a.imm_long(value)), a.fmove_ctrl_out(regs, a.ind(0)), a.fmove_ctrl_in(a.FPCR, a.imm_long(0)), LEA16]
            cases.append(Case(f"ctrl-{name}-{value:08x}", code, long_words(value & mask, 0, 0, 0)))
    for value in ((0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF), (0x00A0, 0x08000000, 0x00F8012C), (0x0400, 0x01000000, 0x1234)):
        code = [a.fmove_ctrl_in(a.FPCR, a.imm_long(0)), a.fmove_ctrl_in(a.FPCR | a.FPSR | a.FPIAR, a.imm_words(*[w for v in value for w in (v >> 16, v & 0xFFFF)])),
                a.fmove_ctrl_out(a.FPCR | a.FPSR | a.FPIAR, a.ind(0)), a.fmove_ctrl_in(a.FPCR, a.imm_long(0)), LEA16]
        cases.append(Case(f"ctrl-all-{value[0]:08x}", code, long_words(value[0] & 0xFFF0, value[1] & 0x0FFFFFF8, value[2], 0)))
    return cases


def movem_cases():
    cases = []
    values = [X(n) for n in (1, 2, 3, 5, 7, 11, 13, 17)]
    load = [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(v), n) for n, v in enumerate(values)]

    def blob(registers):
        return b"".join(long_words(*r.to_words(values[n])) for n in registers)

    def records(data):
        padded = data.ljust(-(-len(data) // RECORD) * RECORD, b"\0")
        return padded, b"\xff" * len(data) + bytes(len(padded) - len(data)), len(padded) // RECORD

    def case(name, registers, body):
        data, mask, count = records(blob(registers))
        cases.append(Case(name, prologue(0) + load + body + ["    .word $41E8,$%04X           ; LEA %d(A0),A0" % (count * RECORD, count * RECORD)], data, mask, records=count))

    everything = list(range(8))
    case("fmovem-out-all", everything, [a.fmovem_out(everything, a.ind(0))])
    case("fmovem-out-predec", everything, ["    .word $43E8,$0060           ; LEA 96(A0),A1", a.fmovem_out(everything, a.predec(1), True)])
    case("fmovem-out-subset", [1, 3, 6], [a.fmovem_out([1, 3, 6], a.ind(0))])
    case("fmovem-out-subset-predec", [1, 3, 6], ["    .word $43E8,$0024           ; LEA 36(A0),A1", a.fmovem_out([1, 3, 6], a.predec(1), True)])
    case("fmovem-out-dynamic", [0, 7], ["    MOVE.L #$81,D0", a.fmovem_dynamic_out(0, a.ind(0))])
    case("fmovem-out-dynamic-predec", [2, 4, 5], ["    .word $43E8,$0024           ; LEA 36(A0),A1", "    MOVE.L #$34,D0", a.fmovem_dynamic_out(0, a.predec(1), True)])
    # memory to registers: three entries saved from FP2, FP4 and FP5 come back into FP0, FP1 and FP7
    reload = [a.fmovem_out([2, 4, 5], a.abs_long(SCRATCH)), a.fmovem_in([0, 1, 7], a.abs_long(SCRATCH)),
              a.fmove_out(a.EXTENDED, 0, a.ind(0)), a.fmove_out(a.EXTENDED, 1, a.disp16(0, 12)), a.fmove_out(a.EXTENDED, 7, a.disp16(0, 24))]
    data, mask, count = records(long_words(*r.to_words(values[2])) + long_words(*r.to_words(values[4])) + long_words(*r.to_words(values[5])))
    cases.append(Case("fmovem-in-subset", prologue(0) + load + reload + ["    .word $41E8,$%04X           ; LEA %d(A0),A0" % (count * RECORD, count * RECORD)], data, mask, records=count))
    return cases


def frame_cases():
    cases = []
    start = SCRATCH + 0x100
    setup = ["    MOVEA.L #$%X,A1" % start, "    .word $4291                 ; CLR.L (A1)", a.frestore(a.ind(1))]
    null_size = 4
    idle_size = {68881: 0x1C, 68882: 0x3C}
    idle_id = {68881: 0x1F180000, 68882: 0x1F380000}
    # FRESTORE of a null frame puts the FPU in the null state, whose FSAVE frame is four bytes of zero
    code = setup + [a.fsave(a.predec(1)), "    .word $2089                 ; MOVE.L A1,(A0)", "    .word $2151,$0004           ; MOVE.L (A1),4(A0)", LEA16]
    # (the null frame of the 6888x is four bytes whose first byte, the version, is zero; what follows it is not fixed by the manual: the engine writes the size of the idle frame)
    cases.append(Case("fsave-null", prologue(0) + code, long_words(start - null_size, 0, 0, 0), b"\xff" * 4 + b"\xff" + bytes(11)))
    # an arithmetic instruction makes the FPU idle: its frame is 28 bytes on the 68881 and 60 on the 68882, with the version and size in its first longword
    code = setup + [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(ONE), 0), a.fsave(a.predec(1)), "    .word $2089                 ; MOVE.L A1,(A0)", "    .word $2151,$0004           ; MOVE.L (A1),4(A0)", LEA16]
    cases.append(Case("fsave-idle", prologue(0) + code, {m: long_words(start - idle_size[m], idle_id[m], 0, 0) for m in (68881, 68882)}))
    # FRESTORE of the frame just saved gives the same frame again
    code = setup + [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(ONE), 0), a.fsave(a.predec(1)), a.frestore(a.postinc(1)), a.fsave(a.predec(1)), "    .word $2089                 ; MOVE.L A1,(A0)",
                    "    .word $2151,$0004           ; MOVE.L (A1),4(A0)", LEA16]
    cases.append(Case("fsave-restore-fsave", prologue(0) + code, {m: long_words(start - idle_size[m], idle_id[m], 0, 0) for m in (68881, 68882)}))
    return cases


EXCEPTIONS = [
    # name, FPCR enable bit, vector, the destination, the operation, its source, the reference result of the operation
    ("dz", 0x0400, 50, ONE, "fdiv", ZP, lambda: r.div(ONE, ZP)),
    ("operr", 0x2000, 52, NEG1, "fsqrt", NEG1, lambda: r.sqrt(NEG1)),
    ("ovfl", 0x1000, 53, MAXF, "fmul", TWO, lambda: r.mul(MAXF, TWO)),
    ("unfl", 0x0800, 51, MINN, "fmul", THIRD, lambda: r.mul(MINN, THIRD)),
    ("snan", 0x4000, 54, ONE, "fadd", SNAN, lambda: r.add(ONE, SNAN)),
    ("inex2", 0x0200, 49, ONE, "fdiv", THREE, lambda: r.div(ONE, THREE)),
]


def marker(register, index):
    return "    .word $%04X,$%04X,$%04X           ; MOVE.L #%d,D%d: marks the instruction after it for the test" % (0x203C | register << 9, index >> 16, index & 0xFFFF, index, register)


ROM_BASE = 0xF80000


def corpus_address(image, word, number):
    """The ROM address of the instruction that follows the marker MOVE.L #number,D<n> (opcode word `word`)."""
    pattern = long_words(word << 16 | number >> 16)[:4] + (number & 0xFFFF).to_bytes(2, "big")
    at = image.find(pattern)
    assert at >= 0 and image.find(pattern, at + 1) < 0, hex(word)
    return ROM_BASE + at


def exception_cases():
    """An enabled exception is posted by the instruction and taken by the next FPU instruction (a pre-instruction exception: format 0 frame, the stacked PC is that next
    instruction); FPIAR holds the address of the instruction that caused it. The expected bytes hold addresses of the program, which the test finds from the markers."""
    cases = []
    high = EXCEPTION_RECORD >> 16
    clear = ["    .word $42B9,$%04X,$%04X           ; CLR.L $%X.L" % (high, (EXCEPTION_RECORD + 4 * i) & 0xFFFF, EXCEPTION_RECORD + 4 * i) for i in range(4)]
    copy = ["    .word $20B9,$%04X,$%04X           ; MOVE.L $%X.L,(A0)" % (high, EXCEPTION_RECORD & 0xFFFF, EXCEPTION_RECORD)] + [
        "    .word $2179,$%04X,$%04X,$%04X     ; MOVE.L $%X.L,%d(A0)" % (high, (EXCEPTION_RECORD + 4 * i) & 0xFFFF, 4 * i, EXCEPTION_RECORD + 4 * i, 4 * i) for i in range(1, 4)]
    for index, (name, enable, vector, dst, op, src, reference) in enumerate(EXCEPTIONS):
        number = 0x100 + index
        fpsr = reference().fpsr
        wide = name in ("ovfl", "unfl", "inex2")               # the condition codes of a result the trap suppresses are not fixed
        first, second = marker(4, number), marker(5, number)
        code = prologue(0) + clear + load_dst(dst) + [a.fmove_ctrl_in(a.FPSR, a.imm_long(0)), a.fmove_ctrl_in(a.FPCR, a.imm_long(enable)), first, a.cpgen_mem(op, a.EXTENDED, ext_imm(src), 0),
                                                       second, a.fnop(), a.fmove_ctrl_in(a.FPCR, a.imm_long(0))] + copy + [LEA16]

        def expected(image, model, number=number, vector=vector, fpsr=fpsr):
            return long_words(corpus_address(image, 0x2A3C, number) + 6, vector * 4, fpsr, corpus_address(image, 0x283C, number) + 6)

        mask = b"\xff" * 8 + (b"\x00\x00\xff\xff" if wide else b"\xff" * 4) + b"\xff" * 4
        cases.append(Case(f"exception-{name}", code, expected, mask))
    # BSUN: a signalling predicate with the NaN bit set is a pre-instruction exception of the branch itself
    number = 0x110
    code = prologue(0) + clear + [a.fmove_ctrl_in(a.FPCR, a.imm_long(0x8000)), a.fmove_ctrl_in(a.FPSR, a.imm_long(r.CC_NAN)), marker(5, number), a.fbcc(0x12, 0),
                                  a.fmove_ctrl_in(a.FPCR, a.imm_long(0))] + copy + [LEA16]

    def bsun(image, model, number=number):
        return long_words(corpus_address(image, 0x2A3C, number) + 6, 48 * 4, r.CC_NAN | r.BSUN | r.AE_IOP, 0)

    cases.append(Case("exception-bsun", code, bsun, b"\xff" * 12 + bytes(4)))
    return cases


def build():
    """-> (assembly text, [Case])."""
    del DATA[:]
    cases = arithmetic_cases() + unary_cases() + other_cases() + conversion_cases() + constant_cases() + condition_cases() + transcendental_cases() + fsincos_cases() + control_cases() + movem_cases() + frame_cases() + exception_cases()
    seen = set()
    for case in cases:
        assert case.name not in seen, case.name
        seen.add(case.name)
    body = []
    for case in cases:
        body.extend(case.code)
    assert sum(case.records for case in cases) * RECORD <= RESULTS_BYTES - 0x100, len(cases)
    table = "".join("%s:\n%s\n" % (label, a.extended_long(x.sign, x.exp, x.man)) for label, x in DATA)
    return PROLOGUE + "\n".join(body) + "\n" + EPILOGUE + table, cases


def result_hash(data):
    """SHA-256 of the records exactly as the program left them (all cases, in order)."""
    return hashlib.sha256(data).hexdigest()
