def neg(x):
    return r.Ext(x.sign ^ 1, x.exp, x.man)


def label(x):
    return "%d.%04x.%016x" % (x.sign, x.exp, x.man)


class Case:
    """The records of one case: `code` (assembler lines that leave `records` records of 16 bytes at (A0) and move A0 past them), `expected` (their bytes, or a dict by FPU model, or
    a function of (image, model) for a result that holds addresses of the program) and `mask` (which bits of them the manual fixes); or, for a function that SoftFloat does not
    round correctly, `close` = [(offset of the result in the records, true value as a Fraction, units in the last place allowed, None)]: only those results and the condition codes
    of FPSR are checked."""

    def __init__(self, name, code, expected, mask=None, close=None, records=1):
        self.name, self.code, self.expected, self.records = name, code, expected, records
        self.mask = mask if mask is not None else b"\xff" * (RECORD * records)
        if isinstance(close, tuple):
            close = [(0,) + close]
        self.close = close

    def __repr__(self):
        return "Case(%s)" % self.name

    def wanted(self, image, model):
        if callable(self.expected):
            return self.expected(image, model)
        return self.expected[model] if isinstance(self.expected, dict) else self.expected


def record(ext, fpsr):
    hi, mid, lo = r.to_words(ext)
    return b"".join(w.to_bytes(4, "big") for w in (hi, mid, lo, fpsr))


def raw_record(payload, fpsr):
    return payload.ljust(12, b"\0") + fpsr.to_bytes(4, "big")


def ext_imm(x):
    return a.imm_words(*a.extended_words(x.sign, x.exp, x.man))


def fpcr_of(prec, mode):
    return prec << 6 | mode << 4


def prologue(fpcr):
    """FPCR is cleared while operands are loaded (a load is never rounded, but nothing here depends on it), then set; FPSR starts clear."""
    return [a.fmove_ctrl_in(a.FPCR, a.imm_long(0))]


def arm(fpcr):
    return [a.fmove_ctrl_in(a.FPCR, a.imm_long(fpcr)), a.fmove_ctrl_in(a.FPSR, a.imm_long(0))]


def finish_ext(register=0):
    return [a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), a.fmove_out(a.EXTENDED, register, a.ind(0)), LEA16]


def load_dst(dst):
    """FP0 = dst. A signalling NaN is loaded with FMOVEM from a table (FMOVE.X from memory or an immediate quiets it and flags SNAN)."""
    if r.is_snan(dst):
        label = "raw%d" % len(DATA)
        DATA.append((label, dst))
        return ["    MOVEA.L #%s,A1" % label, a.fmovem_in([0], a.ind(1))]
    return [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(dst), 0)]


def binary(name, op, dst, src, fpcr=0, expect=None, prec=r.PREC_X, mode=r.RN, masked=False):
    code = prologue(fpcr) + load_dst(dst) + arm(fpcr) + [a.cpgen_mem(op, a.EXTENDED, ext_imm(src), 0)] + finish_ext()
    result = expect if expect is not None else REF[op](dst, src, prec, mode)
    return Case(name, code, record(result.ext, result.fpsr))


def unary(name, op, src, fpcr=0, expect=None, prec=r.PREC_X, mode=r.RN):
    code = prologue(fpcr) + arm(fpcr) + [a.cpgen_mem(op, a.EXTENDED, ext_imm(src), 0)] + finish_ext()
    result = expect if expect is not None else UNARY[op](src, prec, mode)
    return Case(name, code, record(result.ext, result.fpsr))


REF = {
    "fadd": lambda d, s, p, m: r.add(d, s, p, m), "fsub": lambda d, s, p, m: r.sub(d, s, p, m), "fmul": lambda d, s, p, m: r.mul(d, s, p, m),
    "fdiv": lambda d, s, p, m: r.div(d, s, p, m),
}
UNARY = {
    "fsqrt": lambda s, p, m: r.sqrt(s, p, m), "fabs": lambda s, p, m: r.absolute(s), "fneg": lambda s, p, m: r.neg(s), "fint": lambda s, p, m: r.to_integer(s, m),
    "fintrz": lambda s, p, m: r.to_integer(s, m, r.RZ), "fgetexp": lambda s, p, m: r.getexp(s), "fgetman": lambda s, p, m: r.getman(s),
    "fmove": lambda s, p, m: r.move(s, p, m),
}


def both_nan(x, y):
    return r.is_nan(x) and r.is_nan(y)


def arithmetic_cases():
    cases = []
    # 1. Rounding: every mode and every precision on operands whose result is inexact.
    pairs = {
        "fadd": [(ONE, THIRD), (TENTH, X(Fraction(2, 10))), (THREE, X(Fraction(2, 3))), (ONE_PLUS, X(Fraction(1, 3)))],
        "fsub": [(ONE, THIRD), (ONE_PLUS, ONE), (TENTH, X(Fraction(3, 10)))],
        "fmul": [(THIRD, THREE), (TENTH, TENTH), (ONE_PLUS, ONE_PLUS), (X(Fraction(2, 3)), X(Fraction(-5, 7)))],
        "fdiv": [(ONE, THREE), (TEN, SEVEN), (TENTH, THREE), (X(-2), X(Fraction(7, 3)))],
    }
    for op, listing in pairs.items():
        for index, (dst, src) in enumerate(listing):
            for prec in (r.PREC_X, r.PREC_S, r.PREC_D):
                for mode in (r.RN, r.RZ, r.RM, r.RP):
                    cases.append(binary(f"{op}-{index}-{r.PREC_NAME[prec]}{r.MODE_NAME[mode]}", op, dst, src, fpcr_of(prec, mode), prec=prec, mode=mode))
    # 2. Overflow and underflow of the extended range, in every mode.
    for mode in (r.RN, r.RZ, r.RM, r.RP):
        tag = r.MODE_NAME[mode]
        cases.append(binary(f"overflow-mul-{tag}", "fmul", MAXF, TWO, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"overflow-mul-neg-{tag}", "fmul", MAXF, X(-2), fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"overflow-add-{tag}", "fadd", MAXF, MAXF, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"overflow-div-{tag}", "fdiv", MAXF, HALF, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"underflow-mul-{tag}", "fmul", MINN, THIRD, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"underflow-div-{tag}", "fdiv", DEN1, THREE, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"denormal-exact-{tag}", "fmul", MINN, HALF, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"denormal-sub-{tag}", "fsub", r.Ext(0, 1, (1 << 63) | 3), MINN, fpcr_of(0, mode), mode=mode))
    # 3. Exact results and cancellation: the sign of a zero sum depends on the mode.
    for mode in (r.RN, r.RM):
        tag = r.MODE_NAME[mode]
        cases.append(binary(f"cancel-{tag}", "fsub", THIRD, THIRD, fpcr_of(0, mode), mode=mode))
        cases.append(binary(f"cancel-neg-{tag}", "fadd", THIRD, neg(THIRD), fpcr_of(0, mode), mode=mode))
    cases.append(binary("exact-add", "fadd", ONE, ONE))
    cases.append(binary("exact-mul", "fmul", X(Fraction(3, 2)), X(Fraction(5, 4))))
    cases.append(binary("exact-div", "fdiv", X(15), X(5)))
    # 4. Special operands: every pair of {+-0, +-1, +-inf, qNaN, sNaN} for the four operations (both operands NaN is left out).
    for op in ("fadd", "fsub", "fmul", "fdiv"):
        for (dn, dst) in SPECIALS:
            for (sn, src) in SPECIALS:
                if both_nan(dst, src):
                    continue
                cases.append(binary(f"special-{op}-{dn}-{sn}", op, dst, src))
    # 5. Zero divide with a finite dividend of each sign, and 0/0.
    cases.append(binary("div-by-zero-pos", "fdiv", THREE, ZP))
    cases.append(binary("div-by-zero-neg", "fdiv", THREE, ZN))
    cases.append(binary("div-neg-by-zero", "fdiv", X(-3), ZP))
    return cases


def unary_cases():
    cases = []
    roots = [ZP, ZN, ONE, TWO, X(Fraction(1, 4)), THREE, X(Fraction(1, 10000)), MAXF, MINN, DEN1, INFP, NEG1, INFN, QNAN, SNAN, X(Fraction(9, 4)), X(2 ** 64)]
    for index, x in enumerate(roots):
        for prec, mode in ((r.PREC_X, r.RN), (r.PREC_X, r.RZ), (r.PREC_X, r.RP), (r.PREC_D, r.RN), (r.PREC_S, r.RM)):
            if prec != r.PREC_X and (r.is_zero(x) or r.is_nan(x) or r.is_inf(x) or x.exp < 0x3000 or x.exp > 0x7000):
                continue
            cases.append(unary(f"sqrt-{index}-{r.PREC_NAME[prec]}{r.MODE_NAME[mode]}", "fsqrt", x, fpcr_of(prec, mode), prec=prec, mode=mode))
    integers = [ZP, ZN, HALF, X(Fraction(3, 2)), X(Fraction(5, 2)), X(Fraction(-5, 2)), X(Fraction(-1, 2)), X(Fraction(37, 10)), X(Fraction(-37, 10)), X(Fraction(4999, 10000)),
                X(2 ** 63 + 1), X(2 ** 64), ONE_PLUS, MINN, DEN1, INFP, INFN, QNAN, SNAN, X(100)]
    for index, x in enumerate(integers):
        for mode in (r.RN, r.RZ, r.RM, r.RP):
            cases.append(unary(f"int-{index}-{r.MODE_NAME[mode]}", "fint", x, fpcr_of(0, mode), mode=mode))
        cases.append(unary(f"intrz-{index}", "fintrz", x, 0))
    for index, x in enumerate([ONE, X(Fraction(-3, 2)), ZP, ZN, INFP, INFN, QNAN, SNAN, DEN1, MAXF]):
        cases.append(unary(f"abs-{index}", "fabs", x))
        cases.append(unary(f"neg-{index}", "fneg", x))
    for index, x in enumerate([ONE, TENTH, THREE, X(-8), MINN, DEN1, ZP, ZN, INFP, INFN, QNAN, SNAN, MAXF, X(Fraction(3, 4)), neg(THIRD)]):
        cases.append(unary(f"getexp-{index}", "fgetexp", x))
        cases.append(unary(f"getman-{index}", "fgetman", x))
    # FMOVE FPm,FPn rounds to the precision of FPCR.
    for index, x in enumerate([THIRD, TENTH, ONE_PLUS, X(Fraction(-2, 3)), X(10 ** 20), X(Fraction(1, 10 ** 20))]):
        for prec in (r.PREC_S, r.PREC_D):
            for mode in (r.RN, r.RZ, r.RM, r.RP):
                cases.append(unary(f"move-{index}-{r.PREC_NAME[prec]}{r.MODE_NAME[mode]}", "fmove", x, fpcr_of(prec, mode), prec=prec, mode=mode))
    return cases


def other_cases():
    cases = []
    # FSGLMUL and FSGLDIV: single precision result, operands that single precision holds exactly.
    ops = [("fsglmul", r.mul), ("fsgldiv", r.div)]
    single_pairs = [(r.Ext(0, r.BIAS, (1 << 63) | (1 << 40)), r.Ext(0, r.BIAS, (1 << 63) | (1 << 40))), (X(Fraction(3, 2)), X(Fraction(5, 4))), (ONE, THREE)]
    for op, ref in ops:
        for index, (dst, src) in enumerate(single_pairs):
            for mode in (r.RN, r.RZ):
                expect = ref(dst, src, r.PREC_S, mode)
                cases.append(binary(f"{op}-{index}-{r.MODE_NAME[mode]}", op, dst, src, fpcr_of(0, mode), expect=expect))
    # FMOD, FREM and FSCALE with finite operands; the quotient goes to FPSR.
    rem_pairs = [(X(10), THREE), (X(-10), THREE), (X(Fraction(7, 2)), X(Fraction(3, 2))), (X(100), X(7)), (THIRD, TENTH), (X(11), X(2)), (X(13), X(2)), (X(Fraction(5, 2)), ONE)]
    for kind, op in (("mod", "fmod"), ("rem", "frem")):
        for index, (dst, src) in enumerate(rem_pairs):
            result = r.remainder(dst, src, kind)
            cases.append(binary(f"{op}-{index}", op, dst, src, 0, expect=result))
    for index, (dst, src) in enumerate([(ONE, X(10)), (THREE, X(-2)), (THIRD, X(Fraction(7, 2))), (ONE, X(Fraction(-7, 2))), (X(-5), X(3)), (MINN, X(-1)), (HALF, X(-16383))]):
        cases.append(binary(f"fscale-{index}", "fscale", dst, src, 0, expect=r.scale(dst, src)))
    # FCMP and FTST set only the condition codes.
    compares = [(ONE, ONE), (ONE, TWO), (TWO, ONE), (NEG1, ONE), (ZP, ZP), (THIRD, THIRD), (INFP, ONE), (ONE, INFP), (INFP, INFP), (INFN, INFN), (INFN, INFP), (INFP, INFN),
                (QNAN, ONE), (ONE, QNAN)]
    for index, (dst, src) in enumerate(compares):
        result = r.compare(dst, src)
        cases.append(binary(f"fcmp-{index}", "fcmp", dst, src, 0, expect=r.Result(dst, result.fpsr)))
    for index, x in enumerate([ONE, NEG1, ZP, ZN, INFP, INFN, QNAN, SNAN, DEN1]):
        result = r.test(x)
        code = prologue(0) + load_dst(x) + arm(0) + [a.cpgen_reg("ftst", 0, 0)] + finish_ext()
        cases.append(Case(f"ftst-{index}", code, record(result.ext, result.fpsr)))
    return cases


def conversion_cases():
    cases = []
    # FMOVE <ea>,FPn: integers, single and double precision into extended (exact), with the NaN rules.
    for size, fmt, values in (("l", a.LONG, [0, 1, -1, 0x7FFFFFFF, -0x80000000, 123456789]), ("w", a.WORD, [0, 1, -1, 32767, -32768]), ("b", a.BYTE, [0, 1, 127, -128, -1])):
        for value in values:
            bits = {"l": 32, "w": 16, "b": 8}[size]
            raw = value & ((1 << bits) - 1)
            words = [raw >> 16 & 0xFFFF, raw & 0xFFFF] if size == "l" else [raw]
            ext = r.from_integer(value)
            code = prologue(0) + arm(0) + [a.cpgen_mem("fmove", fmt, a.imm_words(*words), 0)] + finish_ext()
            cases.append(Case(f"from-{size}-{value}", code, record(ext, r.finish(ext, 0).fpsr)))
    singles = [0, 0x80000000, 0x3F800000, 0x3DCCCCCD, 0x7F7FFFFF, 0x00800000, 0x00000001, 0x007FFFFF, 0x7F800000, 0xFF800000, 0x7FC00000 | 0x1234, 0x7F800001]
    for bits in singles:
        ext, _ = r.from_single(bits)
        fl = r.SNAN if (bits >> 23 & 0xFF) == 0xFF and bits & 0x7FFFFF and not bits & 0x400000 else 0       # the conversion quiets a signalling NaN and flags it
        code = prologue(0) + arm(0) + [a.cpgen_mem("fmove", a.SINGLE, a.imm_words(bits >> 16, bits & 0xFFFF), 0)] + finish_ext()
        cases.append(Case(f"from-s-{bits:08x}", code, record(ext, r.finish(ext, fl).fpsr)))
    doubles = [0, 0x8000000000000000, 0x3FF0000000000000, 0x3FB999999999999A, 0x7FEFFFFFFFFFFFFF, 0x0010000000000000, 0x0000000000000001, 0x000FFFFFFFFFFFFF, 0x7FF0000000000000,
               0xFFF0000000000000, 0x7FF8000000000000 | 0x1234, 0x7FF0000000000001]
    for bits in doubles:
        ext, _ = r.from_double(bits)
        fl = r.SNAN if (bits >> 52 & 0x7FF) == 0x7FF and bits & (2 ** 52 - 1) and not bits & (1 << 51) else 0
        words = [bits >> 48 & 0xFFFF, bits >> 32 & 0xFFFF, bits >> 16 & 0xFFFF, bits & 0xFFFF]
        code = prologue(0) + arm(0) + [a.cpgen_mem("fmove", a.DOUBLE, a.imm_words(*words), 0)] + finish_ext()
        cases.append(Case(f"from-d-{bits:016x}", code, record(ext, r.finish(ext, fl).fpsr)))
    # FMOVE FPn,<ea>: the integers round in the mode of FPCR and saturate with OPERR; the floats round in the mode too and overflow to infinity or the largest.
    reals = [ZP, ONE, NEG1, X(Fraction(255, 2)), X(Fraction(257, 2)), X(Fraction(-257, 2)), X(Fraction(65535, 2)), X(Fraction(-65537, 2)), X(Fraction(2147483647, 1)),
             X(Fraction(4294967297, 2)), X(Fraction(-4294967297, 2)), X(10 ** 10), X(Fraction(1, 2)), X(Fraction(3, 2)), X(Fraction(5, 2)), X(Fraction(-1, 2)), X(Fraction(-5, 2)),
             X(Fraction(37, 10)), INFP, INFN]
    for index, x in enumerate(reals):
        for size, fmt in (("b", a.BYTE), ("w", a.WORD), ("l", a.LONG)):
            for mode in (r.RN, r.RZ, r.RM, r.RP) if index < 18 else (r.RN,):
                value, exceptions = r.to_integer_format(x, size, mode)
                width = {"b": 1, "w": 2, "l": 4}[size]
                code = prologue(0) + [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(x), 0)] + arm(fpcr_of(0, mode)) + [a.fmove_out(fmt, 0, a.ind(0)), a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
                cases.append(Case(f"to-{size}-{index}-{r.MODE_NAME[mode]}", code, raw_record(value.to_bytes(width, "big"), exceptions | r.accrued(exceptions))))
    floats = [ZP, ZN, ONE, THIRD, TENTH, X(Fraction(-2, 3)), X(10 ** 38), X(10 ** 39), X(Fraction(1, 10 ** 40)), X(2 ** 128), X(2 ** 1024), X(Fraction(1, 2 ** 1030)), INFP, INFN, QNAN, MAXF]
    for index, x in enumerate(floats):
        for size, fmt, convert in (("s", a.SINGLE, r.to_single), ("d", a.DOUBLE, r.to_double)):
            for mode in (r.RN, r.RZ, r.RM, r.RP):
                value, exceptions = convert(x, mode)
                width = 4 if size == "s" else 8
                code = prologue(0) + [a.cpgen_mem("fmove", a.EXTENDED, ext_imm(x), 0)] + arm(fpcr_of(0, mode)) + [a.fmove_out(fmt, 0, a.ind(0)), a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
                cases.append(Case(f"to-{size}-{index}-{r.MODE_NAME[mode]}", code, raw_record(value.to_bytes(width, "big"), exceptions | r.accrued(exceptions))))
    return cases


