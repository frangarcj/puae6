def constant_cases():
    cases = []
    # The constants ROM of the 68881 is not the correctly rounded value of every constant (e = $4000ADF85458A2BB4A9A, one unit below the rounded one), and the manual does
    # not list the bits: each constant is within one unit in the last place of the true value, on the side the rounding mode says, and exact where it is exact (0.0, 1, 10, ...).
    for offset, name in CONSTANTS:
        for mode in ((r.RN, r.RZ, r.RM, r.RP) if name in ("pi", "e", "ln2", "ln10", "log2_e", "log10_e", "log10_2", "ten_32", "ten_64") else (r.RN,)):
            true = r.constant(name)
            ext, _ = r.round_value(true, 0, r.PREC_X, mode)
            code = prologue(0) + arm(fpcr_of(0, mode)) + [a.fmovecr(offset, 0)] + finish_ext()
            exact = r.value(ext) == true
            direction = None          # the directed modes of the ROM are not always on the side the mode says (log10(e) rounded up is below the true value)
            if exact:
                cases.append(Case(f"fmovecr-{offset:02x}-{r.MODE_NAME[mode]}", code, record(ext, r.cc_of(ext)), b"\xff" * 12 + b"\x0f\x00\x00\x00"))
            else:
                cases.append(Case(f"fmovecr-{offset:02x}-{r.MODE_NAME[mode]}", code, record(ext, r.cc_of(ext)), close=(true, 1, direction)))
    return cases


def truth(cc, condition):
    """The predicate of FBcc/FScc (M68881UM table of conditional predicates) for the condition-code bits N Z I NAN."""
    n, z, nan = bool(cc & r.CC_N), bool(cc & r.CC_Z), bool(cc & r.CC_NAN)
    table = [False, z, not (nan or z or n), z or not (nan or n), n and not (nan or z), z or (n and not nan), not (nan or z), not nan, nan, nan or z,
             nan or not (n or z), nan or z or not n, nan or (n and not z), nan or z or n, not z, True]
    return table[condition & 15], (condition >= 16 and nan)


REALIZABLE = {0, r.CC_N, r.CC_Z, r.CC_N | r.CC_Z, r.CC_I, r.CC_N | r.CC_I, r.CC_NAN, r.CC_N | r.CC_NAN}      # what an operation can leave: a NaN is neither zero nor infinite
CC_PATTERNS = [0, r.CC_N, r.CC_Z, r.CC_N | r.CC_Z, r.CC_I, r.CC_N | r.CC_I, r.CC_NAN, r.CC_N | r.CC_NAN, r.CC_Z | r.CC_NAN, r.CC_N | r.CC_Z | r.CC_NAN, r.CC_I | r.CC_NAN,
               r.CC_N | r.CC_I | r.CC_NAN, r.CC_Z | r.CC_I, r.CC_N | r.CC_Z | r.CC_I, r.CC_Z | r.CC_I | r.CC_NAN, r.CC_N | r.CC_Z | r.CC_I | r.CC_NAN]


def condition_cases():
    cases = []
    set_cc = lambda cc: [a.fmove_ctrl_in(a.FPSR, a.imm_long(cc))]          # noqa: E731
    for cc in CC_PATTERNS:
        for condition in range(32):
            value, bsun = truth(cc, condition)
            fpsr = cc | ((r.BSUN | r.AE_IOP) if bsun else 0)
            code = set_cc(cc) + ["    MOVE.L #$12345600,D0", a.fscc(condition, a.dn(0)), "    .word $2080                 ; MOVE.L D0,(A0)",
                                 a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
            # A combination that no operation produces (Z or I together with NAN) is not fixed by the manual: it goes into the hash of the matrix and is not asserted.
            cases.append(Case(f"fscc-{a.CONDITIONS[condition]}-{cc >> 24:x}", code, raw_record((0x12345600 | (0xFF if value else 0)).to_bytes(4, "big"), fpsr),
                              None if cc in REALIZABLE else bytes(RECORD)))
    for cc in (0, r.CC_N, r.CC_Z, r.CC_NAN):
        for condition in range(32):
            value, bsun = truth(cc, condition)
            fpsr = cc | ((r.BSUN | r.AE_IOP) if bsun else 0)
            # FBcc: D0 is 1 when the branch did not jump over the ADDQ
            code = set_cc(cc) + ["    .word $7000                 ; MOVEQ #0,D0", a.fbcc(condition, 2), "    ADDQ.L #1,D0",
                                 "    .word $2080                 ; MOVE.L D0,(A0)", a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
            cases.append(Case(f"fbcc-{a.CONDITIONS[condition]}-{cc >> 24:x}", code, raw_record((0 if value else 1).to_bytes(4, "big"), fpsr)))
            # FDBcc: D1 counts down when the condition is false (and the loop goes on to the next instruction either way)
            code = set_cc(cc) + ["    .word $7203                 ; MOVEQ #3,D1", a.fdbcc(condition, 1, 0),
                                 "    .word $2081                 ; MOVE.L D1,(A0)", a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
            cases.append(Case(f"fdbcc-{a.CONDITIONS[condition]}-{cc >> 24:x}", code, raw_record((3 if value else 2).to_bytes(4, "big"), fpsr)))
            # FTRAPcc: the handler of vector 7 counts in D6
            code = set_cc(cc) + ["    .word $7C00                 ; MOVEQ #0,D6", a.ftrapcc(condition), "    .word $2086                 ; MOVE.L D6,(A0)",
                                 a.fmove_ctrl_out(a.FPSR, a.disp16(0, 12)), LEA16]
            cases.append(Case(f"ftrapcc-{a.CONDITIONS[condition]}-{cc >> 24:x}", code, raw_record((1 if value else 0).to_bytes(4, "big"), fpsr)))
    return cases


