"""The FPU corpus (T54): a micro-ROM of coprocessor instructions with results deduced from the manual, not copied from the engine.

`build()` returns the assembly text of the program and the list of cases. Every case runs one coprocessor instruction (or a short sequence) on the A1200 preset with a
68881 or 68882 and leaves a record of 16 bytes in Chip RAM at $10000 + 16 * index: the result as FMOVE.X writes it (twelve bytes: sign and exponent, a zero word, the
64 bits of significand) or the stored bytes of a conversion, and the FPSR the instruction left (four bytes at offset 12). The expected record of a case is computed in
tests/host/fpu_ref.py with exact rational arithmetic; a case with a mask compares only the bits the manual fixes; a transcendental function is compared with its true
value at a few units in the last place (SoftFloat's FPSP is not correctly rounded) and, whatever its tolerance, every record also goes into one hash (`result_hash`)
that the matrix of platforms (DET04) compares bit for bit.

Not in the corpus on purpose, because the manual does not fix it and a reference derived from it would only be a guess: operations on two NaN operands, results of single
or double precision that fall in the denormal range or overflow, FMOVE.P (packed decimal), the exception frames of a mid-instruction exception, and the timing of the
coprocessor interface.
"""
