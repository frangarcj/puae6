"""T54: the 68881/68882 of the A1200 (SoftFloat in fpp.cpp) runs a micro-ROM of coprocessor instructions and leaves what the manual says.

The expected value of every record is derived in tests/host/fpu_ref.py with exact rational arithmetic from the semantics of the M68881/M68882 User's Manual (rounding
modes and precisions, NaN and infinity rules, the condition codes and the exception and accrued bytes of FPSR); nothing is copied from the engine's output. The program is
generated by tests/host/fpu_corpus.py from the same descriptions, with the coprocessor instructions as `.word` lines whose comments are checked against Capstone's
disassembler when it is installed. The probe links the engine objects of the shared build tree and loads the A1200 preset with an FPU (p6_config.fpu_model).

The same ROM is run by the matrix of platforms (tests/host/fpu_matrix.py, DET04): its results must be the same bit for bit on every row.
"""
import importlib.util
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import unittest

from tests.build_support import build_targets
from tests.host import ensure_generated
from tests.host import fpu_asm
from tests.host import fpu_corpus as corpus
from tests.host import fpu_ref as r

ROOT = Path(__file__).resolve().parents[2]
TREE = ROOT / "build/link-audit"

spec = importlib.util.spec_from_file_location("microrom_builder", ROOT / "tests/fixtures/microrom/build_rom.py")
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)


def compile_probe(tmp):
    objects = sorted(str(p) for p in (TREE / "CMakeFiles/p6_engine.dir").rglob("*.o"))
    include = ["-I" + str(ROOT / d) for d in ("ports/portable", "build/generated", "build/upstream/include", "build/upstream", "bridge/include", "bridge")]
    exe = Path(tmp) / "probe"
    subprocess.run(["clang++", "-std=c++17", "-UNDEBUG", "-O1", "-g", *include, str(ROOT / "tests/host/cpu_fpu_probe.cpp"),
                    *objects, str(TREE / "libp6_bridge.a"), str(TREE / "libp6_portable.a"), "-o", str(exe)], check=True, timeout=300)
    return exe


def run_probe(exe, rom, fpu, units=60, dump=(corpus.RESULTS, corpus.RESULTS_BYTES)):
    result = subprocess.run([str(exe), str(rom), str(units), str(fpu), hex(dump[0]), hex(dump[1])], capture_output=True, text=True, timeout=600)
    lines = [line.split() for line in result.stdout.splitlines()]
    memory = bytearray()
    for line in lines:
        if line[0] == "mem":
            memory += bytes.fromhex(line[2])
    registers = {int(line[1]): (int(line[2], 16), int(line[3], 16)) for line in lines if line[0] == "fpr"}
    return dict(returncode=result.returncode, stderr=result.stderr, lines=lines, memory=bytes(memory), registers=registers)


# The operations whose names the Capstone check compares (the branches and the scc/trap on a condition use predicate names that Capstone gets wrong), and the three names where
# Capstone disagrees with Motorola's opcode table (FSINCOS is read as FSIN, FMOVEM of the control registers as FMOVE, and opmode 9, FTANH, as FATANH; the corpus shows that the
# engine's opmode 9 is the hyperbolic tangent: tanh(1) = 0.76159 within SoftFloat's error).
KNOWN_OPERATIONS = set(fpu_asm.OPMODE) | {"fmovem", "fmovecr", "fsave", "frestore", "fnop", "fsincos"}
CAPSTONE_ALIASES = {"fsincos": {"fsin"}, "fmovem": {"fmovem", "fmove"}, "ftanh": {"fatanh"}}

# Four coprocessor instructions (each is two words) on a machine that may have no FPU; the handler of the line F exception counts and steps over the instruction.
NO_FPU = """; Original PUAE6 micro-ROM, licensed under MIT; see tests/fixtures/microrom/LICENSE.
entry:
    MOVE.W #$2700,SR
    LEA $800.W,A7
    MOVE.B #3,$BFE201.L
    MOVE.B #2,$BFE001.L
    MOVE.L #fline,$2C.L
    MOVE.L #0,D7
    .word $F200,$0422            ; fadd.x fp1,fp0
    .word $F23C,$9000,$0000,$0000 ; fmove.l #0,fpcr  (six bytes: the handler steps over four, and the rest is run as an instruction)
    .word $F200,$0422            ; fadd.x fp1,fp0
    .word $F200,$0422            ; fadd.x fp1,fp0
    MOVE.L D7,$10000.L
    MOVE.L #$600DF00D,$1FFC.L
done:
    BRA.S done
fline:
    ADDQ.L #1,D7
    .word $58AF,$0002            ; ADDQ.L #4,2(A7)
    RTE
"""


class FpuCorpusTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        ensure_generated()
        build_targets(TREE, ["p6_lifecycle_probe"])
        cls.tmp = tempfile.TemporaryDirectory(prefix="p6-fpu-")
        cls.source, cls.cases = corpus.build()
        cls.image = builder.build(cls.source)
        rom = Path(cls.tmp.name) / "fpu.rom"
        rom.write_bytes(cls.image)
        cls.exe, cls.rom = compile_probe(cls.tmp.name), rom
        cls.runs = {model: run_probe(cls.exe, rom, model) for model in (68882, 68881)}

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def header(self, model):
        return next(line for line in self.runs[model]["lines"] if line[0] == "cpu")

    def test_the_probe_ran_the_program_on_a_68020_with_the_fpu_and_softfloat(self):
        for model in (68881, 68882):
            run = self.runs[model]
            self.assertEqual(run["returncode"], 0, run["stderr"])
            self.assertEqual(self.header(model)[1:], ("68020 fpu %d mmu 0 24bit 1 cycle_exact 1 fpu_mode 1" % model).split())
            units = next(line for line in run["lines"] if line[0] == "units")
            self.assertEqual(units[3], "600df00d", "the program did not reach its end")
            self.assertEqual(len(run["memory"]), corpus.RESULTS_BYTES)

    def test_no_instruction_of_the_corpus_took_the_line_f_exception(self):
        for model in (68881, 68882):
            self.assertEqual(struct.unpack(">I", self.runs[model]["memory"][corpus.LINE_F_COUNT - corpus.RESULTS:][:4])[0], 0, model)

    @staticmethod
    def ext_of(record):
        hi, mid, lo, fpsr = struct.unpack(">IIII", record)
        return r.from_words(hi, mid, lo), fpsr

    def check(self, case, got, model):
        """-> None when the records are not what the case says, else the worst error in units in the last place (0 for an exact case)."""
        if case.close is None:
            want = case.wanted(self.image, model)
            return 0.0 if all((g ^ w) & m == 0 for g, w, m in zip(got, want, case.mask)) and len(got) == len(want) else None
        worst = 0.0
        for offset, true, units, direction in case.close:
            ext, fpsr = self.ext_of(got[offset:offset + corpus.RECORD])
            if r.is_nan(ext) or r.is_inf(ext):
                return None
            error = r.ulps(ext, true)
            before = r.value(ext) <= true if direction == "down" else r.value(ext) >= true if direction == "up" else True
            # the condition codes agree with the result, and no exception but the inexact ones was raised
            if not (error <= units and before):
                return None
            if offset == 0 and not (fpsr & 0x0F000000 == r.cc_of(ext) and not fpsr & ~(0x0F000000 | r.INEX2 | r.UNFL | r.OVFL | r.AE_INEX | r.AE_UNFL | r.AE_OVFL)):
                return None            # only the first record of a case holds the FPSR of the instruction
            worst = max(worst, float(error))
        return worst

    def test_every_record_is_what_the_manual_says(self):
        for model in (68882, 68881):
            memory = self.runs[model]["memory"]
            failures, worst, offset = [], 0.0, 0
            for case in self.cases:
                got = memory[offset:offset + case.records * corpus.RECORD]
                offset += case.records * corpus.RECORD
                verdict = self.check(case, got, model)
                if verdict is None:
                    want = case.wanted(self.image, model) if case.close is None else b"within %d ulp" % case.close[0][2]
                    failures.append((case.name, got.hex(), want.hex() if isinstance(want, bytes) and case.close is None else want))
                else:
                    worst = max(worst, verdict)
            for name, got, want in failures[:80]:
                print("MISMATCH %d %-34s got %s want %s" % (model, name, got, want))
            print("%d: worst error of the functions SoftFloat does not round correctly: %.2f ulp" % (model, worst))
            self.assertEqual([], [name for name, _, _ in failures], f"{model}: {len(failures)} of {len(self.cases)} cases differ")

    def test_the_68881_and_the_68882_agree_on_every_record_except_the_frames_of_FSAVE(self):
        offset, different = 0, []
        for case in self.cases:
            size = case.records * corpus.RECORD
            if self.runs[68881]["memory"][offset:offset + size] != self.runs[68882]["memory"][offset:offset + size]:
                different.append(case.name)
            offset += size
        self.assertEqual(["fsave-null", "fsave-idle", "fsave-restore-fsave"], different)

    def test_the_comments_of_the_word_lines_are_what_capstone_disassembles(self):
        """Capstone is an independent disassembler (M68K, with the FPU): the operation named in the comment of every coprocessor `.word` line is the one it reads.
        Branches, scc and trap on a condition are left out (its table of predicates is wrong for FBcc), and so is what it does not know (it prints no mnemonic)."""
        try:
            import capstone
        except ImportError:
            self.skipTest("capstone is not installed")
        md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_BIG_ENDIAN | capstone.CS_MODE_M68K_040)
        checked, seen = 0, set()
        for line in self.source.splitlines():
            match = re.match(r"\s*\.word\s+([^;]+?)\s*;\s*(\S+)", line)
            name = match[2].split(".")[0].lower() if match else ""
            if not match or match[2] in seen or name not in KNOWN_OPERATIONS or not match[1].upper().startswith("$F"):
                continue
            words = [int(w.strip().lstrip("$"), 16) for w in match[1].split(",")]
            text = " ".join(("%s %s" % (i.mnemonic, i.op_str)).strip() for i in md.disasm(b"".join(struct.pack(">H", w) for w in words), 0))
            seen.add(match[2])
            if not text or text.startswith(("dc.w", "invalid")):
                continue
            theirs = text.split()[0].split(".")[0].lower()
            with self.subTest(line=line.strip()):
                self.assertIn(theirs, CAPSTONE_ALIASES.get(name, {name}), line.strip())
            checked += 1
        self.assertGreater(checked, 30)

    def test_without_an_fpu_every_coprocessor_instruction_takes_the_line_f_exception(self):
        source = NO_FPU
        rom = Path(self.tmp.name) / "nofpu.rom"
        rom.write_bytes(builder.build(source))
        counts = {}
        for model in (0, 68881, 68882):
            run = run_probe(self.exe, rom, model, units=20, dump=(0x10000, 0x20))
            self.assertEqual(run["returncode"], 0, run["stderr"])
            counts[model] = struct.unpack(">I", run["memory"][:4])[0]
        self.assertEqual({0: 4, 68881: 0, 68882: 0}, counts)

    def test_the_hash_of_all_the_records_is_pinned_and_printed_for_the_matrix(self):
        total = sum(case.records for case in self.cases) * corpus.RECORD
        digest = corpus.result_hash(self.runs[68882]["memory"][:total])
        golden = json.loads((ROOT / "tests/host/fpu_corpus.golden.json").read_text())
        print("FPU_CORPUS_RESULT_SHA256", digest, len(self.cases), "cases")
        self.assertEqual({"sha256": digest, "cases": len(self.cases), "records": total // corpus.RECORD}, {k: golden[k] for k in ("sha256", "cases", "records")},
                         "the corpus or the results changed: if the change is intended, record the new hash in tests/host/fpu_corpus.golden.json")


if __name__ == "__main__":
    unittest.main()
