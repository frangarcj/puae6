"""Micro-ROMs and scenarios of the T50 machines (A500 OG, A500+, A1000, A2000 OG, A2000), for AV01 and the boot of each preset.

Every expectation comes from the program and from the hardware documentation, never from a capture of the engine:

  clock     MSM6242B at $DC0000, register n at $DC0001 + 4n (the same chip the A500 trapdoor board, the A500+ and the A2000 carry): the program reads the date digits of the
            configured epoch (2000-01-01). A machine without the chip answers with the bus, not with those digits.
  tod       CIA-A TOD low byte, once per vertical blank. On the A500, the A500+ and the A600 the TOD counts the vertical sync, one tick per frame. On the A1000 and the A2000
            it counts the mains: 50 Hz (PAL) or 60 Hz (NTSC), whatever the frame lasts. A PAL frame lasts 312 x 227 colour clocks of 1 / 3546895 s = 19.968 ms (50.08 Hz) and an
            NTSC frame 262 x 227 clocks of 1 / 3579545 s = 16.614 ms (60.19 Hz), so after N frames the mains counted N x 0.99840 (PAL) or N x 0.99685 (NTSC) ticks, less than N.
  chip      the RAM test of tests/scenarios/ecs/ecs.py: four writes above and below 512 KiB, read back. 1 MiB of Chip answers the values written; 512 KiB wraps (address bit 19
            does not exist): the write at $81100 replaces the one at $1100 and $FFFFE is $7FFFE.
  ident     VPOSR / DENISEID (tests/scenarios/ecs/ecs.py): the ECS Agnus reads $2xxx (PAL) or $3xxx (NTSC) and the OCS Agnus $0xxx or $1xxx; only the ECS Denise has the register
            DENISEID ($FFFC).
"""
from tests.scenarios.ecs import ecs

LOG = ecs.LOG
CLOCK_DIGITS = (0x19, 0x1D, 0x21, 0x25, 0x29, 0x2D)          # D1 D10 MO1 MO10 Y1 Y10 from $DC0000 (register n at 4n + 1)
CLOCK_EPOCH_DIGITS = [1, 0, 1, 0, 0, 10]                      # 2000-01-01, the epoch of every test configuration (946684800); the year register holds tm_year / 10 = 10 (rtc.cpp), see test_machines.py

# name -> (chip bytes, slow bytes, Agnus family bits of VPOSR (PAL), ECS Denise?, MSM6242B clock?, mains-driven CIA TOD?)
MACHINES = {
    "A500": (524288, 524288, 0x0000, False, True, False),
    "A600": (1048576, 0, 0x2000, True, False, False),
    "A500OG": (524288, 0, 0x0000, False, False, False),
    "A500PLUS": (1048576, 0, 0x2000, True, True, False),
    "A1000": (524288, 0, 0x0000, False, False, True),
    "A2000OG": (524288, 524288, 0x0000, False, True, True),
    "A2000": (1048576, 0, 0x2000, False, True, True),
}
NEW_MACHINES = ("A500OG", "A500PLUS", "A1000", "A2000OG", "A2000")
PROBE_NAMES = {"A500": "a500", "A600": "a600", "A500OG": "a500og", "A500PLUS": "a500plus", "A1000": "a1000", "A2000OG": "a2000og", "A2000": "a2000"}


def header(what):
    return ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
            "; Generated by tests/scenarios/machines/machines.py: %s." % what,
            "entry:", "    MOVE.W #$2700,SR", "    LEA $400.W,A7",
            "    MOVE.B #3,$BFE201.L", "    MOVE.B #2,$BFE001.L",
            "    LEA $%X.W,A0" % LOG]


def clock_source():
    """Logs the six date digits of the clock chip (one word each, the chip answers in the low nibble) and idles."""
    a = header("the date digits of the MSM6242B")
    for address in CLOCK_DIGITS:
        a += ["    MOVEQ #0,D2", "    MOVE.B $DC00%02X.L,D2" % address, "    MOVE.W D2,(A0)+"]
    a += ["loop:", "    ADDQ.L #1,D0", "    BRA.S loop"]
    return "\n".join(a) + "\n"


TOD_TICKS = 24        # ticks the program times; the run needs a few frames more than that (a tick lasts about a frame)


def tod_source():
    """Starts the CIA-A TOD and times the interval between its ticks with the free-running timer A of CIA-B (E clock, 16 bits, counting down).

    The program polls TODLO with the interrupts off (MOVE.B abs.L,D3; CMP.B D3,D2; BEQ.S back: written as words, the micro-assembler has no compare) and, at each change, logs the
    timer as three byte reads (high, low, high) and the TOD. The alarm interrupt is not used: upstream's CIA-A does not raise it when the tick of a TOD driven by the mains falls
    in the next scanline (cia.cpp CIA_tod_handler, delayed event), which is the same machine and not what this program measures."""
    a = header("the interval between two ticks of the CIA-A TOD, timed by CIA-B timer A")
    a += ["    MOVE.B #$FF,$BFD400.L", "    MOVE.B #$FF,$BFD500.L", "    MOVE.B #$01,$BFDE00.L",            # timer A of CIA-B: latch $FFFF, continuous, started
          "    MOVE.B #$00,$BFEA01.L", "    MOVE.B #$00,$BFE901.L", "    MOVE.B #$00,$BFE801.L",              # TOD = 0 (writing the low byte starts it)
          "    MOVEQ #0,D2", "    MOVEQ #0,D3", "    MOVEQ #0,D4"]
    for _ in range(TOD_TICKS):
        a += ["    MOVE.B $BFE801.L,D3", "    .word $B403", "    .word $67F6",                                    # CMP.B D3,D2; BEQ.S back to the read
              "    .word $1403",                                                                              # MOVE.B D3,D2
              "    MOVE.B $BFD500.L,D4", "    MOVE.W D4,(A0)+", "    MOVE.B $BFD400.L,D4", "    MOVE.W D4,(A0)+",
              "    MOVE.B $BFD500.L,D4", "    MOVE.W D4,(A0)+", "    MOVE.W D3,(A0)+"]
    a += ["loop:", "    ADDQ.L #1,D0", "    BRA.S loop"]
    return "\n".join(a) + "\n"


def tod_periods(words):
    """The interval, in E clocks, between successive TOD alarm interrupts, from the (high, low, high, TOD) quadruples that the handler logs. The timer counts down."""
    stamps = []
    for first, low, second in zip(words[0::4], words[1::4], words[2::4]):
        high = first if (first == second or low >= 128) else second       # the low byte was read before or after the carry into the high one
        stamps.append((high << 8) | low)
    return [(a - b) % 65536 for a, b in zip(stamps, stamps[1:])]


def chip_expected(chip_bytes):
    """The words the RAM test of ecs.chip_ram_prelude reads back: four writes (value, address) then the first location again."""
    if chip_bytes >= 1048576:
        return ecs.chip_ram_expected()
    memory = {}
    for address, value in ecs.RAM_TEST:
        memory[address % chip_bytes] = value
    return [memory[address % chip_bytes] for address, _ in ecs.RAM_TEST + ecs.RAM_TEST[:1]]


def chip_source():
    return ecs.rom_source(ecs.DISPLAYS["chip1m"])


# --- the scenario files (tests/scenarios/machines/machine-*.json) -------------------------------------------------------------------

SCENARIO_UNITS = 6


def scenario_programs():
    """{scenario id: (assembly, units, video standard, machine name)}: ident, clock and chip on each T50 machine in PAL and NTSC."""
    programs = {}
    sources = {"ident": ecs.ident_source(), "clock": clock_source(), "chip": chip_source()}
    for machine in NEW_MACHINES:
        for standard in ("pal", "ntsc"):
            for name, source in sources.items():
                programs["machine-%s-%s-%s" % (PROBE_NAMES[machine], name, standard)] = (source, SCENARIO_UNITS, standard, machine)
    return programs


def scenario_document(scenario_id, rom_sha256, units, standard, machine):
    """The strict-v1 scenario (tools/scenario_schema.py) of a micro-ROM on a machine of the deterministic-a500 profile."""
    idle = {"type": "none", "buttons": 0, "dx": 0, "dy": 0}
    chip, slow = MACHINES[machine][:2]
    return {
        "schema_version": 1, "scenario_id": scenario_id, "profile": "deterministic-a500",
        "config": {"machine": machine, "video_standard": standard.upper(), "audio_rate_hz": 48000, "random_seed": 1,
                   "rtc_epoch_seconds": 946684800, "chip_ram_bytes": chip, "slow_ram_bytes": slow},
        "firmware": [rom_sha256], "media": [], "program": None, "units": units,
        "inputs": [{"unit": 0, "keys": "0" * 32, "ports": [dict(idle), dict(idle)]}],
        "events": [], "checkpoints": list(range(1, units + 1)), "probes": [], "render": True, "audio": True,
    }


if __name__ == "__main__":
    # python3 -m tests.scenarios.machines.machines : (re)writes tests/scenarios/machines/machine-*.json from the programs above
    import hashlib
    import json
    from pathlib import Path
    from tests.step.test_step import builder
    directory = Path(__file__).resolve().parent
    for scenario_id, (source, units, standard, machine) in scenario_programs().items():
        sha = hashlib.sha256(builder.build(source)).hexdigest()
        (directory / (scenario_id + ".json")).write_text(json.dumps(scenario_document(scenario_id, sha, units, standard, machine), indent=2) + "\n", encoding="utf-8")
