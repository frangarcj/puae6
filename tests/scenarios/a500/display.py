"""Display micro-ROMs for the A500 video scenarios, and the picture each one has to produce.

A `Display` is a small hardware program: one bitplane whose single row is repeated on every line (modulo =
minus the row size), a Copper list that recolours COLOR00 at chosen lines, and optionally a VERTB handler that
alternates the foreground colour per field or flips a display mode per unit. `rom_source` writes it as assembly
for tests/fixtures/microrom/build_rom.py. `predict` computes the expected picture from the program alone (no
capture of the engine's output), using the geometry of the canonical raster (docs/adr/0006-video-output.md):

    row r shows Amiga line  first_line + r // 2       first_line = 26 (PAL), 21 (NTSC)
    column c shows lores position 91 + c / 2           DIWSTRT hstart $81 = column 76, DIWSTOP hstop $1C1 = column 716
    the display window covers lines 44 .. 299 (DIWSTRT/DIWSTOP $2C81/$2CC1); the border and the lines outside it
    show COLOR00; OCS colours are 4 bits per channel and become (n << 4) | n.

The raster row is wider than the beam line it starts in: column 0 is colour clock 45.5 of the line and each
column is a quarter of a clock, so from column 742 (clock 231 = clock 4 of the next line) a row already shows the
following line. A Copper colour change at the start of line L+1 therefore appears at the end of row-pair L, which the
model reproduces for PAL. NTSC lines alternate between 227 and 228 clocks, so there the last columns are not described.

Cells the model does not describe (the black blanking margins of the raster) are None.
"""
from dataclasses import dataclass, field

WIDTH = 756
HEIGHT = {"pal": 574, "ntsc": 484}
FIRST_LINE = {"pal": 26, "ntsc": 21}
DIW_FIRST_LINE, DIW_LAST_LINE = 44, 299
FIRST_COLUMN = 76
DIW_COLUMNS = 640
MARGIN = 8            # columns at either end and rows at the bottom the model leaves undescribed
WRAP_COLUMN = 742     # first column that shows the start of the next beam line

# BPLCON0 per mode: one bitplane, colour burst; HIRES = bit 15, LACE = bit 2.
BPLCON0 = {"lores": 0x1200, "hires": 0x9200, "lores_lace": 0x1204, "hires_lace": 0x9204}
DDF = {"lores": 0x003800D0, "hires": 0x003C00D4}
ROW_BYTES = {"lores": 40, "hires": 80}


def rgb(n):
    """OCS 12-bit colour to XRGB8888."""
    r, g, b = (n >> 8) & 15, (n >> 4) & 15, n & 15
    return ((r << 4 | r) << 16) | ((g << 4 | g) << 8) | (b << 4 | b)


@dataclass(frozen=True)
class Display:
    name: str
    mode: str = "lores"                 # lores | hires
    lace: bool = False
    bg: int = 0x000
    fg: int = 0x0F0
    bars: tuple = ()                    # ((first line, COLOR00), ...) applied by the Copper every frame
    pattern: tuple = ()                 # 32-bit words of the row; default: see `row`
    cycle_fg: bool = False              # the VERTB handler puts a new COLOR01 on the screen every unit (counter + $100)
    flip: str = ""                      # "" | "mode" (lores <-> hires) | "lace" (interlace on <-> off) per VERTB

    def row(self):
        words = 20 if (self.mode == "hires" or self.flip == "mode") else 10
        if self.pattern:
            assert len(self.pattern) == words
            return self.pattern
        # First two pixels set, then alternating groups, last two pixels set: edges and interior are visible.
        return (0xC0000000,) + (0x0F0F0F0F, 0xF0F0F0F0) * ((words - 2) // 2) + (0x0F0F0F0F,) * ((words - 2) % 2) + (3,)

    def mode_name(self):
        return self.mode + ("_lace" if self.lace else "")


def rom_source(d):
    """Assembly of the program; a Display is fully described by its fields."""
    mode = d.mode
    a = ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
         "; Generated by tests/scenarios/a500/display.py for the display %s." % d.name,
         "entry:",
         "    MOVE.W #$2700,SR", "    LEA $400.W,A7",
         "    MOVE.B #3,$BFE201.L", "    MOVE.B #2,$BFE001.L"]
    for i, word in enumerate(d.row()):
        a.append("    MOVE.L #$%08X,$%X.L" % (word, 0x20000 + 4 * i))
    a += ["    MOVE.W #$%04X,$DFF180.L" % d.bg, "    MOVE.W #$%04X,$DFF182.L" % d.fg]
    a += ["    MOVE.W #$2C81,$DFF08E.L", "    MOVE.W #$2CC1,$DFF090.L"]
    a += ["    MOVE.L #$%08X,$DFF092.L" % DDF[mode]]
    a += ["    MOVE.L #$%04X%04X,$DFF108.L" % ((-ROW_BYTES[mode]) & 0xFFFF, (-ROW_BYTES[mode]) & 0xFFFF)]
    a += ["    MOVE.L #$00020000,$DFF0E0.L"]
    a += ["    MOVE.W #$%04X,$DFF100.L" % BPLCON0[d.mode_name()]]
    # Copper list at $2000: COLOR00 = bg at the top of every frame, then one WAIT + MOVE per bar, then the end.
    words = [(0x0180, d.bg)]
    for line, color in d.bars:
        assert 0 < line < 256, "bars stay below line 256 so that the WAIT needs no vertical wrap"
        words += [((line << 8) | 1, 0xFFFE), (0x0180, color)]
    words.append((0xFFFF, 0xFFFE))
    for i, (first, second) in enumerate(words):
        a.append("    MOVE.L #$%04X%04X,$%X.L" % (first, second, 0x2000 + 4 * i))
    a += ["    MOVE.L #$2000,$DFF080.L", "    MOVE.W #$8380,$DFF096.L"]     # COP1LC, DMACON: DMAEN | BPLEN | COPEN
    handler = []
    if d.cycle_fg:
        a += ["    MOVE.L #$0100,D1"]                       # D1 is the colour here, not an interrupt count
        handler += ["    MOVE.W D1,$DFF182.L"]
    if d.flip == "mode":
        a += ["    MOVE.L #$%04X,D2" % BPLCON0["lores"], "    MOVE.L #$%04X,D3" % BPLCON0["hires"]]
        a += ["    MOVE.L #$%08X,D4" % DDF["lores"], "    MOVE.L #$%08X,D5" % DDF["hires"]]
        a += ["    MOVE.L #$FFD8FFD8,D6", "    MOVE.L #$FFB0FFB0,D7"]
        handler += ["    EXG D2,D3", "    MOVE.W D2,$DFF100.L", "    EXG D4,D5", "    MOVE.L D4,$DFF092.L",
                    "    EXG D6,D7", "    MOVE.L D6,$DFF108.L"]
    if d.flip == "lace":
        a += ["    MOVE.L #$%04X,D2" % BPLCON0[mode], "    MOVE.L #$%04X,D3" % BPLCON0[mode + "_lace"]]
        handler += ["    EXG D2,D3", "    MOVE.W D2,$DFF100.L"]
    if handler:
        a += ["    MOVE.L #handler,$6C.L", "    MOVE.W #$C020,$DFF09A.L", "    MOVE.W #$2000,SR"]
    a += ["loop:", "    ADDQ.L #1,D0", "    BRA.S loop"]
    if handler:
        a += ["handler:", "    MOVE.W #$0020,$DFF09C.L", "    ADDQ.L #1,D1"] + handler + ["    RTE"]
    return "\n".join(a) + "\n"


def from_rgb(value):
    """12-bit colour of an XRGB8888 pixel made by rgb()."""
    return ((value >> 20) & 15) << 8 | ((value >> 12) & 15) << 4 | ((value >> 4) & 15)


def color_at_line(d, line):
    color = d.bg
    for first, value in d.bars:
        if line >= first:
            color = value
    return color


def predict(d, standard, mode=None, fg=None):
    """Expected XRGB8888 rows for a unit drawn in `mode` (default: the display's own) with foreground `fg`."""
    mode = mode or d.mode
    fg = d.fg if fg is None else fg
    row = d.row()
    height = HEIGHT[standard]
    picture = []
    for r in range(height):
        line = FIRST_LINE[standard] + r // 2
        cells = []
        for c in range(WIDTH):
            if c < MARGIN or c >= WIDTH - MARGIN or r >= height - MARGIN or (standard == "ntsc" and c >= WRAP_COLUMN):
                cells.append(None)
                continue
            background = color_at_line(d, line + 1 if c >= WRAP_COLUMN else line)
            value = background
            if DIW_FIRST_LINE <= line <= DIW_LAST_LINE and FIRST_COLUMN <= c < FIRST_COLUMN + DIW_COLUMNS:
                pixel = (c - FIRST_COLUMN) // 2 if mode == "lores" else c - FIRST_COLUMN
                if row[pixel // 32] >> (31 - pixel % 32) & 1:
                    value = fg
            cells.append(rgb(value))
        picture.append(cells)
    return picture
