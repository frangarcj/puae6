"""Paula micro-ROMs for the audio scenarios.

`Tone` plays a 16-byte square wave (eight bytes of +100, eight of -100) through the audio DMA of the given channels.
Hardware facts used, from the Amiga hardware reference and independent of the engine: the period register counts colour
clocks per byte, bytes are signed 8-bit, the length register counts words, the volume is 0..64, the left output mixes
channels 0 and 3 and the right output channels 1 and 2. With volume 64 one channel puts 100 * 64 * 2 = 12800 at full weight
on its side; the upstream default stereo separation mixes it 26/32 into its own output and 6/32 into the other one:
+-10400 and +-2400.
"""
from dataclasses import dataclass

CHANNEL_BASE = 0xDFF0A0
STEP = 0x10
HIGH_WEIGHT, LOW_WEIGHT = 10400, 2400            # 26/32 and 6/32 of 12800
PAL_CLOCK, NTSC_CLOCK = 3546895, 3579545
CYCLE_UNIT = 512


@dataclass(frozen=True)
class Tone:
    name: str
    channels: tuple = (0,)
    period: int = 200
    volume: int = 64


def rom_source(tone):
    a = ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
         "; Generated by tests/scenarios/audio/audio.py for %s: a square wave through the audio DMA." % tone.name,
         "entry:", "    MOVE.W #$2700,SR", "    LEA $400.W,A7",
         "    MOVE.B #3,$BFE201.L", "    MOVE.B #2,$BFE001.L          ; power LED off: the LED filter stays off",
         "    MOVE.W #$000F,$DFF096.L      ; audio DMA off",
         "    MOVE.L #$64646464,$20000.L", "    MOVE.L #$64646464,$20004.L",
         "    MOVE.L #$9C9C9C9C,$20008.L", "    MOVE.L #$9C9C9C9C,$2000C.L"]
    for ch in tone.channels:
        base = CHANNEL_BASE + STEP * ch
        a += ["    MOVE.L #$20000,$%X.L" % base,              # AUDxLCH/LCL
              "    MOVE.W #8,$%X.L" % (base + 4),             # AUDxLEN: 8 words
              "    MOVE.W #%d,$%X.L" % (tone.period, base + 6),
              "    MOVE.W #%d,$%X.L" % (tone.volume, base + 8)]
    bits = sum(1 << ch for ch in tone.channels)
    a += ["    MOVE.W #$%04X,$DFF096.L      ; DMACON: SET | DMAEN | AUDxEN" % (0x8200 | bits),
          "loop:", "    ADDQ.L #1,D0", "    BRA.S loop"]
    return "\n".join(a) + "\n"


def frames_bound(master_ticks, rate, clock):
    """(exact, low, high): stereo frames produced by a boundary at `master_ticks`, from the clock alone.

    Paula emits sample k at tick floor(k * I + 1/2) after the anchor at tick 2048 (the first audio setup in the reset head, four
    colour clocks in), with I = clock * 512 / rate ticks held as a float32 that is a multiple of 1/256: I = m / 256. The
    portable form, which needs neither constant, is floor(master_ticks * rate / (clock * 512)) - 1 .. that value."""
    m = (2 * clock * 131072 + rate) // (2 * rate)
    exact = (256 * (master_ticks - 2048) + 127) // m
    high = master_ticks * rate // (clock * CYCLE_UNIT)
    return exact, high - 1, high
