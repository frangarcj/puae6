"""T24b: the A1200 preset (68EC020 cycle exact, AGA, 2 MiB Chip, no Gayle) identifies itself, has 2 MiB of Chip RAM and runs 68020 code.

A micro-ROM (generated here) reads VPOSR and DENISEID at power-on and at every VERTB, writes and reads back four places in 2 MiB of
Chip RAM, runs a few 68020 instructions and takes its VERTB interrupt through a VBR that is not zero. Every expected value comes
from the program and the documentation, never from a capture of the engine:

  VPOSR     bits 14..8: Agnus identity. The upstream table (custom.cpp VPOSR) gives the AGA Alice $23 (the Amiga hardware
            documentation lists $22 and $23 for the two Alice revisions) and sets bit 12 for an NTSC machine: $23xx PAL, $33xx NTSC.
  DENISEID  $DFF07C: the AGA Lisa reads $00F8 (the ECS Denise $FFFC, the A4000 $FCF8; custom.cpp DENISEID).
  Chip RAM  2 MiB: $100000-$1FFFFF are real Chip RAM, not an alias of the first mebibyte (the A600 has 1 MiB, the A500 512 KiB).
  68020     EXTB.L, MULU.L, DIVS.L, BFEXTU and MOVEC CACR/VBR, with the results the MC68020 User's Manual defines; the long list of
            instructions is tests/host/test_cpu_020.py, which runs the same core on this machine.

The same program runs in the steps mode and in the continuous mode of the STEP01 probe: p6_run_frame is the only scheduler, so the two
must agree unit by unit.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import tempfile
import unittest

from tests.step.test_ecs import log_words
from tests.step.test_step import TOOLS, builder, configure_trace_tree, frames_of, run_probe

VPOSR, DENISEID = 0xDFF004, 0xDFF07C
LOG = 0x1000
VBR = 0x4000
RAM_TEST = ((0x1100, 0xAAAA), (0x101100, 0x5555), (0x181100, 0x1234), (0x1FFFFE, 0x9ABC))
# Offsets 0x1100 and 0x101100 are the same modulo 1 MiB: an A600-sized Chip would alias them and the second write would replace the first.
M32 = 0xFFFFFFFF


def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def expected_020():
    """The longs the program logs, from the semantics of the instructions."""
    extb = 0xFD - 0x100 & M32                                  # EXTB.L D0 with D0 = $123456FD: byte $FD sign extended
    mulu = (0x12345 * 0x6789) & M32                            # MULU.L D1,D0 (32-bit result)
    divs = trunc_div(-1000000, 7) & M32                        # DIVS.L D1,D0, quotient rounded towards zero
    bfextu = (0x0ABCDEF1 << 4 & M32) >> 24                     # BFEXTU D1{4:8},D2: eight bits from bit offset 4 (MSB side)
    return [extb, mulu, divs, bfextu, 1, VBR]                  # CACR written 1 reads 1 (EI); VBR written $4000 reads $4000


def program():
    a = ["; Original PUAE6 micro-ROM, licensed under MIT; see LICENSE.",
         "; Generated by tests/step/test_a1200.py: identity, 2 MiB of Chip RAM, a few 68020 instructions, VERTB through VBR.",
         "entry:", "    MOVE.W #$2700,SR", "    LEA $400.W,A7",
         "    MOVE.B #3,$BFE201.L", "    MOVE.B #2,$BFE001.L",
         "    LEA $%X.W,A0" % LOG,
         "    MOVE.W $%X.L,(A0)+" % VPOSR, "    MOVE.W $%X.L,(A0)+" % DENISEID]
    for address, value in RAM_TEST:
        a.append("    MOVE.W #$%04X,$%X.L" % (value, address))
    for address, _ in RAM_TEST + RAM_TEST[:1]:
        a.append("    MOVE.W $%X.L,(A0)+" % address)
    a += ["    MOVE.L #$123456FD,D0", "    .word $49C0                  ; extb.l d0", "    MOVE.L D0,(A0)+",
          "    MOVE.L #$12345,D0", "    MOVE.L #$6789,D1", "    .word $4C01,$0000            ; mulu.l d1,d0", "    MOVE.L D0,(A0)+",
          "    MOVE.L #-1000000,D0", "    MOVEQ #7,D1", "    .word $4C41,$0800            ; divs.l d1,d0", "    MOVE.L D0,(A0)+",
          "    MOVE.L #$0ABCDEF1,D1", "    .word $E9C1,$2108            ; bfextu d1{4:8},d2", "    MOVE.L D2,(A0)+",
          "    MOVEQ #1,D0", "    .word $4E7B,$0002            ; movec d0,cacr", "    .word $4E7A,$1002            ; movec cacr,d1",
          "    MOVE.L D1,(A0)+",
          "    MOVE.L #$%X,D0" % VBR, "    .word $4E7B,$0801            ; movec d0,vbr", "    .word $4E7A,$1801            ; movec vbr,d1",
          "    MOVE.L D1,(A0)+",
          "    MOVE.L #handler,$%X.L" % (VBR + 0x6C),
          "    MOVE.W #$0200,$DFF100.L",                              # colour burst, no bitplane
          "    MOVE.W #$C020,$DFF09A.L", "    MOVE.W #$2000,SR",
          "loop:", "    ADDQ.L #1,D0", "    BRA.S loop",
          "handler:", "    MOVE.W #$0020,$DFF09C.L",
          "    MOVE.W $%X.L,(A0)+" % VPOSR, "    MOVE.W $%X.L,(A0)+" % DENISEID, "    RTE"]
    return "\n".join(a) + "\n"


def longs(words):
    return [words[i] << 16 | words[i + 1] for i in range(0, len(words), 2)]


@unittest.skipUnless(TOOLS, "toolchain unavailable")
class A1200MicroRomTests(unittest.TestCase):
    UNITS = 6

    @classmethod
    def setUpClass(cls):
        cls.exe = configure_trace_tree()
        cls.tmp = tempfile.TemporaryDirectory(prefix="p6-a1200-")
        cls.rom = Path(cls.tmp.name) / "a1200.rom"
        cls.rom.write_bytes(builder.build(program()))

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def run_rom(self, standard, mode="frames", units=None):
        code, out = run_probe(self.exe, self.rom, units or self.UNITS, mode, 1, timeout=600, extra=[standard, "a1200"],
                              env={"P6_DUMP_LOG": "1", "P6_UNIT_LIMIT_LINES": "6000"})
        self.assertEqual(code, 0, out[-600:])
        return out

    def words(self, standard):
        units = log_words(self.run_rom(standard))
        return [w for unit in sorted(units) for w in units[unit]]

    def test_alice_and_lisa_identify_themselves_at_power_on_and_at_every_vertical_blank(self):
        # The vector at $6C is never set: only the table at VBR + $6C has the handler, so every pair after the power-on read proves that the
        # interrupt was taken through the relocated vector table.
        for standard in ("pal", "ntsc"):
            words = self.words(standard)
            head = 2 + len(RAM_TEST) + 1 + 2 * len(expected_020())
            pairs = [(words[0], words[1])] + list(zip(words[head::2], words[head + 1::2]))
            with self.subTest(standard=standard):
                self.assertGreaterEqual(len(pairs), 5)                    # the power-on read and one per VERTB
                for vposr, deniseid in pairs:
                    self.assertEqual(vposr & 0x7F00, 0x3300 if standard == "ntsc" else 0x2300, hex(vposr))
                    self.assertEqual(deniseid, 0x00F8)

    def test_chip_ram_is_two_mebibytes_and_not_an_alias(self):
        for standard in ("pal", "ntsc"):
            words = self.words(standard)
            with self.subTest(standard=standard):
                self.assertEqual(words[2:2 + len(RAM_TEST) + 1], [v for _, v in RAM_TEST] + [RAM_TEST[0][1]])

    def test_the_68020_instructions_leave_what_the_manual_says(self):
        for standard in ("pal", "ntsc"):
            words = self.words(standard)
            start = 2 + len(RAM_TEST) + 1
            with self.subTest(standard=standard):
                self.assertEqual(longs(words[start:start + 2 * len(expected_020())]), expected_020())

    def test_n_calls_equal_continuous_advance(self):
        def compare(job):
            standard, units = job
            return job, [self.run_rom(standard, mode, units) for mode in ("steps", "continuous")]
        jobs = [(standard, units) for standard in ("pal", "ntsc") for units in (3, 7)]
        with ThreadPoolExecutor(max_workers=4) as pool:
            for job, (steps, continuous) in pool.map(compare, jobs):
                with self.subTest(job=job):
                    self.assertEqual(steps, continuous)

    def test_every_unit_delivers_the_buffer_of_an_ecs_or_aga_machine(self):
        # A programmed beam may turn the NTSC configuration into a PAL raster: the buffer reserves the PAL height (ADR 0006).
        for standard in ("pal", "ntsc"):
            rows = frames_of(self.run_rom(standard))
            with self.subTest(standard=standard):
                self.assertEqual(len(rows), self.UNITS)
                self.assertEqual({(r[5], r[6]) for r in rows}, {(760, 576)})


if __name__ == "__main__":
    unittest.main()
