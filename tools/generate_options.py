#!/usr/bin/env python3
"""Validate config/schema/options.json and generate what is derived from it (T17b).

    python3 tools/generate_options.py            # write the generated files
    python3 tools/generate_options.py --check    # fail if a committed generated file is stale

Outputs, never edited by hand:
  adapters/libretro/options_generated.h        the libretro core options (v2 with categories, v1, and the legacy SET_VARIABLES strings), the
                                               Settings the core fills from them and how Settings becomes a p6_config
  config/schema/options_table.generated.json   the table that headless and the BizHawk wrapper must respect: the normalized p6_config
                                               defaults and allowed values, and where each adapter takes its value from

Value sets. Several options may offer the same long list of values (the 24 RetroPad mapper options all choose among the same targets); the schema
lists them once under "value_sets" and an option says "values_from": NAME. load_schema copies the set into the option's "values", so everything downstream
(validation, normalization, the outputs) sees an ordinary enum; the generated header emits the set once and gives each of its entries with a "const" name a
constant (p6_options::k<Set><Const>) so that no adapter types a number the schema owns.

The module is also a library: load_schema, validate_schema and normalize_config (one request for a configuration, checked against the
schema with a diagnostic that names the key and the value), which tests/config uses.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "config/schema/options.json"
HEADER = ROOT / "adapters/libretro/options_generated.h"
TABLE = ROOT / "config/schema/options_table.generated.json"
P6_HEADER = ROOT / "bridge/include/p6.h"

# p6_config fields that are not choices of ABI v1: they have one valid value (checked by bridge/config.cpp validate_config).
FIXED_CONFIG_FIELDS = {"abi_version", "struct_size", "reserved32", "reserved7"}
REBOOT_SENTENCE = " It takes effect the next time the content is loaded; the running machine is not changed."
REBOOT_SUFFIX = " (Restart)"
MAX_VALUES = 128      # RETRO_NUM_CORE_OPTION_VALUES_MAX
INT_TYPES = {"u64": ("uint64_t", 0, 2**64 - 1), "i64": ("int64_t", -2**63, 2**63 - 1)}
IDENTIFIER = re.compile(r"[a-z][a-z0-9_]*\Z")
LIBRETRO_KEY = re.compile(r"puae6_[a-z][a-z0-9_]*\Z")
PRESET_KEY = "puae6_preset"       # the one libretro key that is no option of the schema: it selects one of the schema's presets
PREAMBLE = ("Generated by tools/generate_options.py from config/schema/options.json. Do not edit by hand: change the schema and run "
            "the generator (python3 tools/generate_options.py --check fails when this file is stale).")


class SchemaError(ValueError):
    """The schema is malformed; the message lists every problem found."""


class ConfigError(ValueError):
    """A requested configuration is not one the schema supports; the message names the key and the value."""


def load_schema(path: Path = SCHEMA) -> dict:
    schema = json.loads(Path(path).read_text(encoding="utf-8"))
    expand_value_sets(schema)
    return schema


def expand_value_sets(schema: dict) -> None:
    """Gives every option that says values_from its values (a copy of the set, which validate_schema then checks like any other list)."""
    sets = schema.get("value_sets") if isinstance(schema, dict) else None
    for option in (schema.get("options") if isinstance(schema, dict) else None) or []:
        if isinstance(option, dict) and isinstance(option.get("values_from"), str) and "values" not in option:
            if not isinstance(sets, dict) or option["values_from"] not in sets:
                raise SchemaError(f"option '{option.get('id')}': values_from names the value set {option['values_from']!r}, which the schema does not have")
            option["values"] = json.loads(json.dumps(sets[option["values_from"]]))


def p6_config_fields(header: Path = P6_HEADER) -> list[str]:
    """The member names of struct p6_config in the ABI header."""
    text = header.read_text(encoding="utf-8")
    body = re.search(r"typedef struct p6_config \{(.*?)\} p6_config;", text, re.S)
    if not body:
        raise SchemaError(f"{header}: struct p6_config not found")
    names = []
    for line in body[1].splitlines():
        match = re.match(r"\s*(?:u?int(?:8|16|32|64)_t)\s+(\w+)(?:\[\d+\])?;", line)
        if match:
            names.append(match[1])
    return names


# --- validation ------------------------------------------------------------------------------------------------------------------------

def _text(value, minimum=1) -> bool:
    return isinstance(value, str) and len(value.strip()) >= minimum and value.isascii() and value == value.strip()


def _only(obj, allowed, required, where, errors):
    if not isinstance(obj, dict):
        errors.append(f"{where}: must be an object")
        return False
    for key in sorted(set(obj) - set(allowed)):
        errors.append(f"{where}: unknown field '{key}'")
    missing = sorted(set(required) - set(obj))
    for key in missing:
        errors.append(f"{where}: missing field '{key}'")
    return not missing        # an object that lacks a required field is not looked at further


def validate_schema(schema: dict, config_fields: list[str] | None = None) -> None:
    """Raise SchemaError, listing every problem, unless the schema is complete and consistent. `config_fields` are the members of p6_config
    (by default read from bridge/include/p6.h): every one of them must be mapped by an option or be a fixed field of ABI v1."""
    errors: list[str] = []
    if not _only(schema, {"schema_version", "about", "categories", "value_sets", "options", "presets", "selectors", "reserved", "unsupported"},
                 {"schema_version", "categories", "options", "presets", "reserved", "unsupported"}, "schema", errors):
        raise SchemaError("\n".join(errors))
    if schema.get("schema_version") != 1:
        errors.append("schema: schema_version must be 1")
    if "about" in schema and not (isinstance(schema["about"], list) and all(_text(line) for line in schema["about"])):
        errors.append("schema: about must be a list of ASCII lines")

    categories: set[str] = set()
    for i, category in enumerate(schema.get("categories") or []):
        where = f"categories[{i}]"
        if not _only(category, {"id", "label", "info"}, {"id", "label", "info"}, where, errors):
            continue
        if not (isinstance(category["id"], str) and IDENTIFIER.fullmatch(category["id"])):
            errors.append(f"{where}: id must be lowercase letters, digits and underscores")
        elif category["id"] in categories:
            errors.append(f"{where}: duplicate category '{category['id']}'")
        categories.add(str(category["id"]))
        for field in ("label", "info"):
            if not _text(category[field]):
                errors.append(f"{where}: {field} must be non-empty ASCII text")

    _validate_value_sets(schema.get("value_sets", {}), errors)
    ids: set[str] = set()
    keys: set[str] = set()
    mapped: dict[str, str] = {}
    for i, option in enumerate(schema.get("options") or []):
        name = option.get("id") if isinstance(option, dict) else None
        where = f"option '{name}'" if isinstance(name, str) else f"options[{i}]"
        allowed = {"id", "class", "type", "maps_to", "default", "values", "min", "max", "libretro", "libretro_policy", "headless", "wrapper", "restart", "values_from"}
        if not _only(option, allowed, {"id", "class", "type", "maps_to", "default", "libretro", "headless", "wrapper"}, where, errors):
            continue
        if not (isinstance(name, str) and IDENTIFIER.fullmatch(name)):
            errors.append(f"{where}: id must be lowercase letters, digits and underscores")
        elif name in ids:
            errors.append(f"{where}: duplicate option id")
        ids.add(str(name))
        kind, klass, maps_to = option["type"], option["class"], option["maps_to"]
        if klass not in ("reboot", "presentation"):
            errors.append(f"{where}: class must be 'reboot' or 'presentation', not {klass!r}")
        if "restart" in option and not (option["restart"] is True and klass == "presentation"):
            errors.append(f"{where}: restart is true or absent, and only a presentation option has it (one the core reads when the content is loaded and cannot apply in place)")
        if kind not in ("enum", "u64", "i64"):
            errors.append(f"{where}: type must be 'enum', 'u64' or 'i64', not {kind!r}")
        if not (isinstance(maps_to, str) and re.fullmatch(r"(p6_config|presentation)\.[a-z][a-z0-9_]*", maps_to)):
            errors.append(f"{where}: maps_to must be 'p6_config.FIELD' or 'presentation.NAME'")
        else:
            target, _, field = maps_to.partition(".")
            if klass == "reboot" and target != "p6_config":
                errors.append(f"{where}: a reboot option must map to a p6_config field (it enters config_hash), not '{maps_to}'")
            if klass == "presentation" and (target != "presentation" or field != name):
                errors.append(f"{where}: a presentation option has no effect on emulation, so it maps to 'presentation.{name}', not '{maps_to}'")
            if target == "p6_config":
                if config_fields is not None and field not in config_fields:
                    errors.append(f"{where}: p6_config has no field '{field}'")
                if field in FIXED_CONFIG_FIELDS:
                    errors.append(f"{where}: p6_config.{field} has one valid value in ABI v1 and is not a choice")
            if maps_to in mapped:
                errors.append(f"{where}: maps_to '{maps_to}' is already used by option '{mapped[maps_to]}'")
            mapped[maps_to] = str(name)
        if "values_from" in option:
            shared = (schema.get("value_sets") or {}).get(option["values_from"])
            if option["type"] != "enum" or shared is None or option.get("values") != shared:
                errors.append(f"{where}: values_from must name a value set of the schema, and the values of an enum must be that set (load_schema copies it)")
        _validate_values(option, kind, where, errors)
        _validate_libretro(option, kind, where, categories, keys, errors)
        _validate_adapters(option, klass, where, errors)

    _validate_presets(schema, errors)
    _validate_selectors(schema, errors, keys)
    for i, entry in enumerate(schema.get("reserved") or []):
        where = f"reserved[{i}]"
        if _only(entry, {"id", "for", "wrapper_setting", "why"}, {"id", "for", "wrapper_setting", "why"}, where, errors):
            if not (isinstance(entry["id"], str) and IDENTIFIER.fullmatch(entry["id"])) or entry["id"] in ids:
                errors.append(f"{where}: id must be new lowercase letters, digits and underscores")
            ids.add(str(entry["id"]))
            for field in ("for", "wrapper_setting", "why"):
                if not _text(entry[field]):
                    errors.append(f"{where}: {field} must be non-empty ASCII text")
    seen_unsupported: set[str] = set()
    for i, entry in enumerate(schema.get("unsupported") or []):
        where = f"unsupported[{i}]"
        if _only(entry, {"key", "why"}, {"key", "why"}, where, errors):
            key = entry["key"]
            if not (isinstance(key, str) and IDENTIFIER.fullmatch(key)):
                errors.append(f"{where}: key must be lowercase letters, digits and underscores")
            elif key in seen_unsupported or key in ids:
                errors.append(f"{where}: '{key}' is already an option or listed as unsupported")
            seen_unsupported.add(str(key))
            if not _text(entry["why"]):
                errors.append(f"{where}: why must be non-empty ASCII text")

    if config_fields is not None:
        for field in config_fields:
            if field not in FIXED_CONFIG_FIELDS and f"p6_config.{field}" not in mapped:
                errors.append(f"p6_config.{field} is not covered: map an option to it or declare it fixed in tools/generate_options.py")
    if errors:
        raise SchemaError("\n".join(errors))


def _validate_value_sets(sets, errors):
    """A value set is a list of values shared by several options: each has a name, a 32-bit number and a label, and may name a constant for the generated header."""
    if not isinstance(sets, dict):
        errors.append("schema: value_sets must be an object")
        return
    for name, values in sets.items():
        where = f"value set '{name}'"
        if not (isinstance(name, str) and IDENTIFIER.fullmatch(name)):
            errors.append(f"{where}: the name must be lowercase letters, digits and underscores")
        if not (isinstance(values, list) and values):
            errors.append(f"{where}: must be a non-empty list of values")
            continue
        names, abis, consts = set(), set(), set()
        for j, value in enumerate(values):
            if not _only(value, {"value", "abi", "label", "const"}, {"value", "abi", "label"}, f"{where} values[{j}]", errors):
                continue
            if not _text(value["value"]) or not _text(value["label"]):
                errors.append(f"{where} values[{j}]: value and label must be non-empty ASCII text")
            if value["value"] in names:
                errors.append(f"{where}: duplicate value '{value['value']}'")
            names.add(value["value"])
            abi = value["abi"]
            if not (isinstance(abi, int) and not isinstance(abi, bool) and 0 <= abi < 2**32):
                errors.append(f"{where} values[{j}]: abi must be an integer of 32 bits")
            elif abi in abis:
                errors.append(f"{where}: duplicate abi value {abi}")
            abis.add(abi)
            if "const" in value:
                if not (isinstance(value["const"], str) and re.fullmatch(r"[A-Z][A-Za-z0-9]*", value["const"])):
                    errors.append(f"{where} values[{j}]: const must be a CamelCase identifier")
                elif value["const"] in consts:
                    errors.append(f"{where}: duplicate const '{value['const']}'")
                consts.add(str(value["const"]))
        if len(values) > MAX_VALUES - 1:
            errors.append(f"{where}: libretro takes at most {MAX_VALUES - 1} values and ends the list with an empty one")


def _validate_presets(schema, errors):
    """A preset is a named bundle of values of reboot enum options (the model and its memory); it must name the machine, and every value must be one the option has."""
    options = _option_index(schema) if all(isinstance(o, dict) and "id" in o for o in schema.get("options") or []) else {}
    seen: set[str] = set()
    for i, preset in enumerate(schema.get("presets") or []):
        where = f"presets[{i}]"
        if not _only(preset, {"id", "label", "values", "note"}, {"id", "label", "values", "note"}, where, errors):
            continue
        if not (isinstance(preset["id"], str) and IDENTIFIER.fullmatch(preset["id"])) or preset["id"] in seen or preset["id"] == "none":
            errors.append(f"{where}: id must be new lowercase letters, digits and underscores, and not 'none'")
        seen.add(str(preset["id"]))
        for field in ("label", "note"):
            if not _text(preset[field]):
                errors.append(f"{where}: {field} must be non-empty ASCII text")
        values = preset["values"]
        if not (isinstance(values, dict) and "machine" in values):
            errors.append(f"{where}: values must be an object that names at least the machine")
            continue
        for name, value in values.items():
            option = options.get(name)
            if not option or option.get("class") != "reboot" or option.get("type") != "enum":
                errors.append(f"{where}: '{name}' is not a reboot enum option")
            elif value not in [v.get("value") for v in option.get("values", [])]:
                errors.append(f"{where}: '{value}' is not a value of {name}")
    if len(seen) + 1 > MAX_VALUES:
        errors.append(f"presets: libretro takes at most {MAX_VALUES} values")


def _validate_values(option, kind, where, errors):
    if kind == "enum":
        values = option.get("values")
        if "min" in option or "max" in option:
            errors.append(f"{where}: an enum has no min/max")
        if not (isinstance(values, list) and values):
            errors.append(f"{where}: an enum needs a non-empty values list")
            return
        names, abis = set(), set()
        for j, value in enumerate(values):
            if not _only(value, {"value", "abi", "abi_name", "label", "wrapper", "wrapper_name", "const"}, {"value", "abi", "label"}, f"{where} values[{j}]", errors):
                continue
            if "wrapper" in value and (value["wrapper"] is not False or not (isinstance(option.get("wrapper"), dict) and option["wrapper"].get("how") == "setting")):
                errors.append(f"{where} values[{j}]: wrapper may only be false (the BizHawk wrapper does not offer this value), on an option the wrapper takes as a setting")
            if not _text(value["value"]) or not _text(value["label"]):
                errors.append(f"{where} values[{j}]: value and label must be non-empty ASCII text")
            if value["value"] in names:
                errors.append(f"{where}: duplicate value '{value['value']}'")
            names.add(value["value"])
            abi = value["abi"]
            if not (isinstance(abi, int) and not isinstance(abi, bool) and 0 <= abi < 2**32):
                errors.append(f"{where} values[{j}]: abi must be an integer of 32 bits")
            elif abi in abis:
                errors.append(f"{where}: duplicate abi value {abi}")
            abis.add(abi)
            if "wrapper_name" in value and not (isinstance(value["wrapper_name"], str) and re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", value["wrapper_name"])):
                errors.append(f"{where} values[{j}]: wrapper_name must be the C# identifier of the member of the wrapper's enum (the value itself when it is not a number)")
            if "abi_name" in value and not (isinstance(value["abi_name"], str) and re.fullmatch(r"P6_[A-Z0-9_]+", value["abi_name"])):
                errors.append(f"{where} values[{j}]: abi_name must be a P6_ constant name")
        if option["default"] not in names:
            errors.append(f"{where}: default {option['default']!r} is not one of the values {sorted(names)}")
    elif kind in INT_TYPES:
        _, lowest, highest = INT_TYPES[kind]
        if "values" in option:
            errors.append(f"{where}: a number has min/max, not a values list")
        low, high, default = option.get("min"), option.get("max"), option["default"]
        ints = all(isinstance(x, int) and not isinstance(x, bool) for x in (low, high, default))
        if not ints:
            errors.append(f"{where}: min, max and default must be integers")
        elif not (lowest <= low <= default <= high <= highest):
            errors.append(f"{where}: default {default} is not within min {low} and max {high} ({kind})")


def _validate_libretro(option, kind, where, categories, keys, errors):
    libretro = option["libretro"]
    if libretro is None:
        if not _text(option.get("libretro_policy"), 20):
            errors.append(f"{where}: a key that libretro does not offer needs a libretro_policy that says why")
        return
    if "libretro_policy" in option:
        errors.append(f"{where}: libretro_policy is only for a key libretro does not offer")
    if kind != "enum":
        errors.append(f"{where}: libretro offers enums only (a number would need a free-form field the frontends do not have)")
    if not _only(libretro, {"key", "category", "label", "info", "extra_values", "default"}, {"key", "category", "label", "info"}, f"{where} libretro", errors):
        return
    _validate_libretro_extras(option, libretro, where, errors)
    key = libretro["key"]
    if not (isinstance(key, str) and LIBRETRO_KEY.fullmatch(key)):
        errors.append(f"{where}: libretro key must be 'puae6_' and lowercase letters, digits and underscores")
    elif key in keys:
        errors.append(f"{where}: duplicate libretro key '{key}'")
    keys.add(str(key))
    if libretro["category"] not in categories:
        errors.append(f"{where}: libretro category '{libretro['category']}' is not declared")
    for field in ("label", "info"):
        if not _text(libretro[field]):
            errors.append(f"{where}: libretro {field} must be non-empty ASCII text")
    if isinstance(option.get("values"), list) and len(option["values"]) > MAX_VALUES:
        errors.append(f"{where}: libretro takes at most {MAX_VALUES} values")


def _validate_libretro_extras(option, libretro, where, errors):
    """T76: values only the libretro core offers (the automatic ones: the core resolves them to a value of the option before the machine is made) and the libretro default.
    An extra value has a name, a number that is no value of the option (it never reaches p6_config), a label and a CamelCase constant for the generated header."""
    names = {v.get("value") for v in option.get("values", []) if isinstance(v, dict)}
    abis = {v.get("abi") for v in option.get("values", []) if isinstance(v, dict)}
    extras = libretro.get("extra_values", [])
    if not isinstance(extras, list):
        errors.append(f"{where}: libretro extra_values must be a list")
        return
    seen_names, seen_abis, consts = set(), set(), set()
    for j, extra in enumerate(extras):
        label = f"{where} libretro extra_values[{j}]"
        if not _only(extra, {"value", "abi", "label", "const"}, {"value", "abi", "label", "const"}, label, errors):
            continue
        if not _text(extra["value"]) or not _text(extra["label"]):
            errors.append(f"{label}: value and label must be non-empty ASCII text")
        if extra["value"] in names or extra["value"] in seen_names:
            errors.append(f"{label}: '{extra['value']}' is already a value of the option")
        seen_names.add(extra["value"])
        abi = extra["abi"]
        if not (isinstance(abi, int) and not isinstance(abi, bool) and 0 <= abi < 2**32):
            errors.append(f"{label}: abi must be an integer of 32 bits")
        elif abi in abis or abi in seen_abis:
            errors.append(f"{label}: the number {abi} is already used by a value of the option (an extra value never reaches p6_config, so it needs a number of its own)")
        seen_abis.add(abi)
        if not (isinstance(extra["const"], str) and re.fullmatch(r"[A-Z][A-Za-z0-9]*", extra["const"])) or extra["const"] in consts:
            errors.append(f"{label}: const must be a new CamelCase identifier")
        consts.add(str(extra["const"]))
    if extras and option.get("type") != "enum":
        errors.append(f"{where}: only an enum has extra libretro values")
    if "default" in libretro and libretro["default"] not in names | seen_names:
        errors.append(f"{where}: libretro default {libretro['default']!r} is not a value of the option or an extra one")


def _validate_selectors(schema, errors, taken_keys):
    """T76: choices only the libretro core has (they pick the machine before it is made and are no p6_config field): the model for floppy and for hard disk content and
    the switch of the file name tags. Each shapes like an option of the libretro menu: a key, a category, values with a number, a default."""
    options = _option_index(schema) if all(isinstance(o, dict) and "id" in o for o in schema.get("options") or []) else {}
    ids, keys = set(), set(taken_keys)
    categories = {c.get("id") for c in schema.get("categories") or [] if isinstance(c, dict)}
    for i, selector in enumerate(schema.get("selectors") or []):
        where = f"selectors[{i}]"
        if not _only(selector, {"id", "default", "values", "values_of", "libretro"}, {"id", "default", "libretro"}, where, errors):
            continue
        name = selector["id"]
        if not (isinstance(name, str) and IDENTIFIER.fullmatch(name)) or name in ids or name in options or name == "preset":
            errors.append(f"{where}: id must be a new lowercase identifier")
        ids.add(str(name))
        if ("values" in selector) == ("values_of" in selector):
            errors.append(f"{where}: give either values or values_of (the id of an option whose values are taken)")
            continue
        if "values_of" in selector:
            source = options.get(selector["values_of"])
            if not source or source.get("type") != "enum" or source.get("class") != "reboot":
                errors.append(f"{where}: values_of must name a reboot enum option")
                continue
            values = source["values"]
        else:
            values = selector["values"]
            if not (isinstance(values, list) and values):
                errors.append(f"{where}: values must be a non-empty list")
                continue
            names, abis = set(), set()
            for j, value in enumerate(values):
                if _only(value, {"value", "abi", "label"}, {"value", "abi", "label"}, f"{where} values[{j}]", errors):
                    if value["value"] in names or value["abi"] in abis or not _text(value["value"]) or not _text(value["label"]) or not isinstance(value["abi"], int) or isinstance(value["abi"], bool):
                        errors.append(f"{where} values[{j}]: a new name, a new integer number and a label")
                    names.add(value["value"])
                    abis.add(value["abi"])
        if selector["default"] not in [v.get("value") for v in values]:
            errors.append(f"{where}: default {selector['default']!r} is not one of the values")
        libretro = selector["libretro"]
        if _only(libretro, {"key", "category", "label", "info"}, {"key", "category", "label", "info"}, f"{where} libretro", errors):
            if not (isinstance(libretro["key"], str) and LIBRETRO_KEY.fullmatch(libretro["key"])) or libretro["key"] in keys or libretro["key"] == PRESET_KEY:
                errors.append(f"{where}: libretro key must be a new 'puae6_' key")
            keys.add(str(libretro["key"]))
            if libretro["category"] not in categories:
                errors.append(f"{where}: libretro category '{libretro['category']}' is not declared")
            for field in ("label", "info"):
                if not _text(libretro[field]):
                    errors.append(f"{where}: libretro {field} must be non-empty ASCII text")


def _validate_adapters(option, klass, where, errors):
    headless, wrapper = option["headless"], option["wrapper"]
    if _only(headless, {"how", "flag", "sets", "names"}, {"how"}, f"{where} headless", errors):
        how = headless["how"]
        if how not in ("flag", "value", "choice", "named", "kib", "fixed", "none", "profile"):
            errors.append(f"{where}: headless how must be flag, value, choice, named, kib, fixed, profile or none")
        needed = {"flag": {"flag", "sets"}, "value": {"flag"}, "choice": {"flag", "names"}, "named": {"flag", "names"}, "kib": {"flag"}}.get(how, set())
        if set(headless) - {"how"} != needed:
            errors.append(f"{where}: headless '{how}' takes exactly the fields {sorted(needed)}")
        if how == "kib" and option["type"] != "enum":
            errors.append(f"{where}: headless 'kib' is for the memory sizes, which are enums")
        if how == "flag" and option["type"] == "enum" and headless.get("sets") not in [v.get("value") for v in option.get("values", [])]:
            errors.append(f"{where}: headless flag sets {headless.get('sets')!r}, which is not a value")
        if how in ("choice", "named") and "names" in headless:
            names = headless["names"]
            values = [v.get("value") for v in option.get("values", [])] if option["type"] == "enum" else []
            if not (isinstance(names, dict) and sorted(names) == sorted(values) and all(_text(spelling) and spelling == spelling.lower() for spelling in names.values())
                    and len(set(names.values())) == len(names)):
                errors.append(f"{where}: headless '{how}' names every value of an enum once, in lowercase ASCII (the spelling after the flag)")
        if (klass == "presentation" and how not in ("none", "value", "named")) or (klass == "reboot" and how == "none"):
            errors.append(f"{where}: headless 'none' is for presentation options only (a reboot option is part of the machine headless runs)")
    if _only(wrapper, {"how", "setting", "type", "where"}, {"how"}, f"{where} wrapper", errors):
        how = wrapper["how"]
        if how not in ("setting", "fixed", "none", "profile"):
            errors.append(f"{where}: wrapper how must be setting, fixed, profile or none")
        needed = {"setting": {"setting", "type"}, "fixed": {"where"}}.get(how, set())
        if set(wrapper) - {"how"} != needed:
            errors.append(f"{where}: wrapper '{how}' takes exactly the fields {sorted(needed)}")
        if (klass == "presentation" and how not in ("none", "setting")) or (klass == "reboot" and how == "none"):
            errors.append(f"{where}: wrapper 'none' is for presentation options only")


# --- normalization: one requested configuration against the schema ---------------------------------------------------------------------

def _option_index(schema: dict) -> dict:
    return {option["id"]: option for option in schema["options"]}


def normalize_value(option: dict, raw) -> object:
    """The normalized value of `raw` for `option`: the value name for an enum, an integer for a number. ConfigError otherwise."""
    name = option["id"]
    if option["type"] == "enum":
        names = [value["value"] for value in option["values"]]
        if not isinstance(raw, str) or raw not in names:
            raise ConfigError(f"option {name}: the value {raw!r} is not supported (allowed: {', '.join(names)})")
        return raw
    # At most 64 digits: int() refuses a longer text with a bare ValueError (a limit that depends on the Python version) that does not name the option.
    if isinstance(raw, str) and re.fullmatch(r"-?[0-9]{1,64}", raw):
        raw = int(raw)
    if not isinstance(raw, int) or isinstance(raw, bool) or not option["min"] <= raw <= option["max"]:
        raise ConfigError(f"option {name}: the value {raw!r} is not an integer from {option['min']} to {option['max']}")
    return raw


def normalize_config(schema: dict, requested: dict) -> dict:
    """Every option with a value: the requested one, normalized, or the schema's default. A key that is not in the schema is refused with the
    reason when it is a known-unsupported one (CPU, RAM, ROM, other machines) and as unknown otherwise; nothing is half-accepted."""
    if not isinstance(requested, dict):
        raise ConfigError(f"the requested configuration must be a mapping of option names to values, not {type(requested).__name__}")
    options = _option_index(schema)
    unsupported = {entry["key"]: entry["why"] for entry in schema["unsupported"]}
    reserved = {entry["id"]: entry for entry in schema["reserved"]}
    problems = []
    for key in requested:
        if key in options:
            continue
        if key in unsupported:
            problems.append(f"option {key} is not supported: {unsupported[key]}")
        elif key in reserved:
            problems.append(f"option {key} is not available yet: {reserved[key]['why']}")
        else:
            problems.append(f"option {key} is unknown (supported: {', '.join(options)})")
    result = {}
    for name, option in options.items():
        try:
            result[name] = normalize_value(option, requested[name]) if name in requested else option["default"]
        except ConfigError as error:
            problems.append(str(error))
    if problems:
        raise ConfigError("\n".join(problems))
    return result


def apply_preset(schema: dict, normalized: dict, preset: str) -> dict:
    """`normalized` with the values of the preset `preset` laid over it ('none' leaves it alone). ConfigError for an id the schema does not have."""
    if preset == "none":
        return dict(normalized)
    found = next((entry for entry in schema["presets"] if entry["id"] == preset), None)
    if not found:
        raise ConfigError(f"preset {preset!r} is not one of: none, {', '.join(entry['id'] for entry in schema['presets'])}")
    return {**normalized, **found["values"]}


def abi_value(option: dict, normalized) -> int:
    """The number that goes into the p6_config field (or, for presentation, into Settings) for a normalized value."""
    if option["type"] == "enum":
        return next(value["abi"] for value in option["values"] if value["value"] == normalized)
    return normalized


def to_p6_config(schema: dict, normalized: dict) -> dict:
    """The p6_config fields (name -> number) that a normalized configuration produces."""
    return {option["maps_to"].partition(".")[2]: abi_value(option, normalized[option["id"]])
            for option in schema["options"] if option["maps_to"].startswith("p6_config.")}


# --- generated header ------------------------------------------------------------------------------------------------------------------

def _c(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _camel(identifier: str) -> str:
    return "".join(part.capitalize() for part in identifier.split("_"))


def _field_type(option: dict) -> str:
    return "uint32_t" if option["type"] == "enum" else INT_TYPES[option["type"]][0]


def _literal(option: dict, value: int) -> str:
    return {"enum": f"{value}u", "u64": f"UINT64_C({value})", "i64": f"INT64_C({value})"}[option["type"]]


def _lr_values(option: dict) -> list:
    """The values libretro offers for an option: the automatic ones only the core has (T76, libretro.extra_values) first, then the option's own."""
    return list((option["libretro"].get("extra_values") or [])) + list(option["values"])


def _lr_default(option: dict) -> str:
    """The value libretro starts with (T76: the automatic one for the model and the video standard, which the core resolves before the machine is made)."""
    return option["libretro"].get("default", option["default"])


def _lr_abi(option: dict, name: str) -> int:
    return next(v["abi"] for v in _lr_values(option) if v["value"] == name)


def _inline_values(option: dict) -> str:
    """The {value, label} initializers of a libretro definition: the set's macro when the option shares a set, else the list."""
    if "values_from" in option:
        return f"P6_SET_{option['values_from'].upper()}_V2"
    return ", ".join(f"{{{_c(v['value'])}, {_c(v['label'])}}}" for v in _lr_values(option))


def _needs_reload(option: dict) -> bool:
    """A reboot option, or a presentation option the core reads when the content is loaded (restart): a change made while it runs only applies after a reload."""
    return option["class"] == "reboot" or bool(option.get("restart"))


def _description(option: dict) -> tuple[str, str]:
    """The label and the help text a frontend shows; a reboot option says so in both."""
    libretro = option["libretro"]
    reboot = _needs_reload(option)
    return libretro["label"] + (REBOOT_SUFFIX if reboot else ""), libretro["info"] + (REBOOT_SENTENCE if reboot else "")


def _preset_entry(schema: dict) -> dict:
    """The libretro option that selects a preset, shaped like an option of the schema (it is not one: it has no p6_config field of its own)."""
    labels = "; ".join(f"{entry['label']}: {entry['note']}" for entry in schema["presets"])
    return {"id": "preset", "class": "reboot", "default": "none",
            "values": [{"value": "none", "abi": 0, "label": "None (the model and the memory options below)"}] +
                      [{"value": entry["id"], "abi": n, "label": entry["label"]} for n, entry in enumerate(schema["presets"], 1)],
            "libretro": {"key": PRESET_KEY, "category": "machine", "label": "Preset",
                         "info": "A model and its memory in one choice, over the Model and the memory options (PUAE5-like machines). " + labels}}


def _selector_entries(schema: dict) -> list:
    """The libretro choices that are no option of the schema (T76: the model of the floppy and of the hard disk content, the file name tags), shaped like an option."""
    options = _option_index(schema)
    entries = []
    for selector in schema.get("selectors") or []:
        values = options[selector["values_of"]]["values"] if "values_of" in selector else selector["values"]
        entries.append({"id": selector["id"], "class": "reboot", "default": selector["default"], "libretro": selector["libretro"],
                        "values": [{"value": v["value"], "abi": v["abi"], "label": v["label"]} for v in values]})
    return entries


def _libretro_entries(schema: dict) -> list:
    """The options libretro offers, in menu order: the preset and the selectors come right after the model."""
    entries = []
    for option in schema["options"]:
        if option["libretro"]:
            entries.append(option)
            if option["id"] == "machine":
                entries.append(_preset_entry(schema))
                entries.extend(_selector_entries(schema))
    return entries


def _apply_preset_function(schema: dict) -> list:
    options = _option_index(schema)
    lines = ["// The number of each preset in Settings.preset (0 is none).",
             *[f"constexpr uint32_t kPreset{_camel(entry['id'])} = {n}u;" for n, entry in enumerate(schema["presets"], 1)],
             "",
             "// Lays the preset the person chose over the model and the memory options (read_options calls it once everything is read).",
             "inline void apply_preset(Settings *settings)", "{", "    switch (settings->preset) {"]
    for n, entry in enumerate(schema["presets"], 1):
        lines.append(f"    case {n}u:  // {entry['id']}")
        for name, value in entry["values"].items():
            lines.append(f"        settings->{name} = {abi_value(options[name], value)}u;")
        lines.append("        break;")
    lines += ["    default:", "        break;", "    }", "}"]
    return lines


def generate_header(schema: dict) -> str:
    options = schema["options"]
    exposed = _libretro_entries(schema)
    out: list[str] = []
    w = out.append
    w(f"// {PREAMBLE}")
    w("#ifndef P6_LIBRETRO_OPTIONS_GENERATED_H")
    w("#define P6_LIBRETRO_OPTIONS_GENERATED_H")
    w("")
    w('#include "libretro.h"')
    w('#include "p6.h"')
    w("")
    w("#include <stdint.h>")
    w("")
    w("namespace p6_options {")
    w("")
    w("// Every key of the schema with its default. The reboot keys are p6_config fields (to_config); the presentation keys never reach the")
    w("// machine. A key libretro does not offer keeps its default here, which is the only value the core ever uses for it.")
    w("struct Settings {")
    for option in options:
        name = _lr_default(option) if option["libretro"] else option["default"]
        default = _lr_abi(option, name) if option["libretro"] and option["type"] == "enum" else abi_value(option, option["default"])
        note = f"  // {option['class']}, {option['maps_to']}" + (f" = {name}" if option["type"] == "enum" else "")
        if option["libretro"] and name != option["default"]:
            note += f" (libretro starts automatic; the schema's default for the other adapters is {option['default']})"
        w(f"    {_field_type(option)} {option['id']} = {_literal(option, default)};{note}")
    w("    uint32_t preset = 0u;  // reboot, a bundle of the options above (the schema's presets, apply_preset); 0 = none. Not a p6_config field")
    for selector in _selector_entries(schema):
        w(f"    uint32_t {selector['id']} = {_lr_abi(selector, selector['default'])}u;  // reboot, a libretro choice that is no p6_config field (the schema's selectors) = {selector['default']}")
    w("};")
    w("")
    w("inline void to_config(const Settings &settings, p6_config *config)")
    w("{")
    for option in options:
        if option["class"] == "reboot":
            w(f"    config->{option['maps_to'].partition('.')[2]} = settings.{option['id']};")
    w("}")
    w("")
    out.extend(_apply_preset_function(schema))
    w("")
    w("// The options libretro offers: the value names the frontend stores and the number each stands for in Settings.")
    w("struct Value {")
    w("    const char *name;")
    w("    uint32_t number;")
    w("};")
    w("")
    w("struct Option {")
    w("    const char *key;")
    w("    bool reboot;                        // a change needs a reload and is never applied to the running one: a reboot option (part of the machine) or a restart one (read at load)")
    w("    uint32_t Settings::*field;")
    w("    const Value *values;")
    w("    unsigned count;")
    w("    unsigned default_index;")
    w("};")
    w("")
    for option in options:
        for extra in (option["libretro"] or {}).get("extra_values") or []:
            w(f"constexpr uint32_t k{_camel(option['id'])}{extra['const']} = {extra['abi']}u;       // {option['libretro']['key']}={extra['value']}: resolved by the core before the machine is made")
    for name, values in (schema.get("value_sets") or {}).items():
        w(f"// The value set {name}: one list for every option that says values_from.")
        w(f"constexpr Value k{_camel(name)}SetValues[] = {{")
        for value in values:
            w(f"    {{{_c(value['value'])}, {value['abi']}u}},")
        w("};")
        for value in values:
            if "const" in value:
                w(f"constexpr uint32_t k{_camel(name)}{value['const']} = {value['abi']}u;")
        names = "|".join(v["value"] for v in values)
        pairs = ", ".join(f"{{{_c(v['value'])}, {_c(v['label'])}}}" for v in values)
        w(f"#define P6_SET_{name.upper()}_V2 {pairs}")
        w(f"#define P6_SET_{name.upper()}_LEGACY {_c(names)}")
    for option in exposed:
        if "values_from" in option:
            continue
        w(f"constexpr Value k{_camel(option['id'])}Values[] = {{")
        for value in _lr_values(option):
            w(f"    {{{_c(value['value'])}, {value['abi']}u}},")
        w("};")
    w("")
    w("constexpr Option kOptions[] = {")
    for option in exposed:
        index = [v["value"] for v in _lr_values(option)].index(_lr_default(option))
        values = f"k{_camel(option['values_from'])}SetValues" if "values_from" in option else f"k{_camel(option['id'])}Values"
        w(f"    {{{_c(option['libretro']['key'])}, {'true' if _needs_reload(option) else 'false'}, &Settings::{option['id']}, {values}, "
          f"{len(_lr_values(option))}, {index}}},")
    w("};")
    w("constexpr unsigned kOptionCount = sizeof kOptions / sizeof kOptions[0];")
    w("")
    w("// retro_core_option_v2: categories and definitions, each array ends with an empty element.")
    w("// Not const: libretro's structs take non-const pointers. The frontend only reads them.")
    w("inline retro_core_option_v2_category kCategoriesV2[] = {")
    for category in schema["categories"]:
        w(f"    {{{_c(category['id'])}, {_c(category['label'])}, {_c(category['info'])}}},")
    w("    {nullptr, nullptr, nullptr},")
    w("};")
    w("")
    w("inline retro_core_option_v2_definition kDefinitionsV2[] = {")
    for option in exposed:
        desc, info = _description(option)
        values = _inline_values(option)
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc)}, {_c(desc)},")
        w(f"     {_c(info)},")
        w(f"     {_c(info)},")
        w(f"     {_c(option['libretro']['category'])}, {{{values}}}, {_c(_lr_default(option))}}},")
    w("    {nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, {}, nullptr},")
    w("};")
    w("inline retro_core_options_v2 kOptionsV2 = {kCategoriesV2, kDefinitionsV2};")
    w("")
    w("// retro_core_option (version 1): no categories.")
    w("constexpr retro_core_option_definition kDefinitionsV1[] = {")
    for option in exposed:
        desc, info = _description(option)
        values = _inline_values(option)
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc)}, {_c(info)}, {{{values}}}, {_c(_lr_default(option))}}},")
    w("    {nullptr, nullptr, nullptr, {}, nullptr},")
    w("};")
    w("")
    w("// Legacy SET_VARIABLES: \"Description; default|other|...\" (the default comes first).")
    w("constexpr retro_variable kVariables[] = {")
    for option in exposed:
        desc, _ = _description(option)
        names = [v["value"] for v in _lr_values(option)]
        if "values_from" in option and names[0] == option["default"]:      # the set's own text, written once
            w(f"    {{{_c(option['libretro']['key'])}, {_c(desc + '; ')} P6_SET_{option['values_from'].upper()}_LEGACY}},")
            continue
        names.remove(_lr_default(option))
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc + '; ' + '|'.join([_lr_default(option)] + names))}}},")
    w("    {nullptr, nullptr},")
    w("};")
    w("")
    w("}  // namespace p6_options")
    w("")
    for name in (schema.get("value_sets") or {}):
        w(f"#undef P6_SET_{name.upper()}_V2")
        w(f"#undef P6_SET_{name.upper()}_LEGACY")
    w("")
    w("#endif")
    return "\n".join(out) + "\n"


def generate_table(schema: dict) -> str:
    """The table adapters must respect: the p6_config fields as numbers, and how each adapter takes its value."""
    config, presentation, adapters = {}, {}, {}
    for option in schema["options"]:
        if option["type"] == "enum" and "values_from" in option:
            entry = {"default": abi_value(option, option["default"]), "values_from": option["values_from"]}
        elif option["type"] == "enum":
            allowed = [value["abi"] for value in option["values"]]
            entry = {"default": abi_value(option, option["default"]), "allowed": allowed,
                     "names": {value["value"]: value["abi"] for value in option["values"]}}
        else:
            entry = {"default": option["default"], "min": option["min"], "max": option["max"]}
        entry["option"] = option["id"]
        entry["class"] = option["class"]
        if option.get("restart"):
            entry["restart"] = True
        (config if option["class"] == "reboot" else presentation)[option["maps_to"].partition(".")[2]] = entry
        adapters[option["id"]] = {"headless": option["headless"], "wrapper": option["wrapper"],
                                  "libretro": option["libretro"]["key"] if option["libretro"] else None}
        if option["libretro"] and (option["libretro"].get("extra_values") or "default" in option["libretro"]):
            adapters[option["id"]]["libretro_default"] = _lr_default(option)
            adapters[option["id"]]["libretro_extra_values"] = {v["value"]: v["abi"] for v in option["libretro"].get("extra_values") or []}
        withheld = [value["value"] for value in option.get("values", []) if value.get("wrapper") is False]
        if withheld:
            adapters[option["id"]]["wrapper_not_offered"] = withheld
    document = {"generated_by": PREAMBLE, "p6_config": config, "presentation": presentation,
                "value_sets": {name: {value["value"]: value["abi"] for value in values} for name, values in (schema.get("value_sets") or {}).items()},
                "adapters": adapters,
                "presets": {entry["id"]: {"label": entry["label"], "values": entry["values"]} for entry in schema["presets"]},
                "selectors": {entry["id"]: {"libretro": entry["libretro"]["key"], "default": entry["default"], "values": {v["value"]: v["abi"] for v in entry["values"]}}
                              for entry in _selector_entries(schema)},
                "reserved": {entry["id"]: entry["wrapper_setting"] for entry in schema["reserved"]},
                "unsupported": {entry["key"]: entry["why"] for entry in schema["unsupported"]}}
    return json.dumps(document, indent=2, sort_keys=False) + "\n"


def outputs(schema: dict) -> dict[Path, str]:
    return {HEADER: generate_header(schema), TABLE: generate_table(schema)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file differs from what the schema produces")
    parser.add_argument("--schema", type=Path, default=SCHEMA)
    parser.add_argument("--header", type=Path, default=HEADER)
    parser.add_argument("--table", type=Path, default=TABLE)
    args = parser.parse_args(argv)
    try:
        schema = load_schema(args.schema)
        validate_schema(schema, p6_config_fields())
    except (SchemaError, OSError, json.JSONDecodeError) as error:
        print(f"{args.schema}: {error}", file=sys.stderr)
        return 1
    generated = {args.header: generate_header(schema), args.table: generate_table(schema)}
    status = 0
    for path, text in generated.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                print(f"{path}: {'missing' if current is None else 'stale'}; run python3 tools/generate_options.py", file=sys.stderr)
                status = 1
        elif current != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    return status


if __name__ == "__main__":
    sys.exit(main())
