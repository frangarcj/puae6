#!/usr/bin/env python3
"""Validate config/schema/options.json and generate what is derived from it (T17b).

    python3 tools/generate_options.py            # write the generated files
    python3 tools/generate_options.py --check    # fail if a committed generated file is stale

Outputs, never edited by hand:
  adapters/libretro/options_generated.h        the libretro core options (v2 with categories, v1, and the legacy SET_VARIABLES strings), the
                                               Settings the core fills from them and how Settings becomes a p6_config
  config/schema/options_table.generated.json   the table that headless and the BizHawk wrapper must respect: the normalized p6_config
                                               defaults and allowed values, and where each adapter takes its value from

The module is also a library: load_schema, validate_schema and normalize_config (one request for a configuration, checked against the
schema with a diagnostic that names the key and the value), which tests/config uses.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "config/schema/options.json"
HEADER = ROOT / "adapters/libretro/options_generated.h"
TABLE = ROOT / "config/schema/options_table.generated.json"
P6_HEADER = ROOT / "bridge/include/p6.h"

# p6_config fields that are not choices of ABI v1: they have one valid value (checked by bridge/config.cpp validate_config).
FIXED_CONFIG_FIELDS = {"abi_version", "struct_size", "reserved"}
REBOOT_SENTENCE = " It takes effect the next time the content is loaded; the running machine is not changed."
REBOOT_SUFFIX = " (Restart)"
MAX_VALUES = 128      # RETRO_NUM_CORE_OPTION_VALUES_MAX
INT_TYPES = {"u64": ("uint64_t", 0, 2**64 - 1), "i64": ("int64_t", -2**63, 2**63 - 1)}
IDENTIFIER = re.compile(r"[a-z][a-z0-9_]*\Z")
LIBRETRO_KEY = re.compile(r"puae6_[a-z][a-z0-9_]*\Z")
PREAMBLE = ("Generated by tools/generate_options.py from config/schema/options.json. Do not edit by hand: change the schema and run "
            "the generator (python3 tools/generate_options.py --check fails when this file is stale).")


class SchemaError(ValueError):
    """The schema is malformed; the message lists every problem found."""


class ConfigError(ValueError):
    """A requested configuration is not one the schema supports; the message names the key and the value."""


def load_schema(path: Path = SCHEMA) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def p6_config_fields(header: Path = P6_HEADER) -> list[str]:
    """The member names of struct p6_config in the ABI header."""
    text = header.read_text(encoding="utf-8")
    body = re.search(r"typedef struct p6_config \{(.*?)\} p6_config;", text, re.S)
    if not body:
        raise SchemaError(f"{header}: struct p6_config not found")
    names = []
    for line in body[1].splitlines():
        match = re.match(r"\s*(?:u?int(?:8|16|32|64)_t)\s+(\w+)(?:\[\d+\])?;", line)
        if match:
            names.append(match[1])
    return names


# --- validation ------------------------------------------------------------------------------------------------------------------------

def _text(value, minimum=1) -> bool:
    return isinstance(value, str) and len(value.strip()) >= minimum and value.isascii() and value == value.strip()


def _only(obj, allowed, required, where, errors):
    if not isinstance(obj, dict):
        errors.append(f"{where}: must be an object")
        return False
    for key in sorted(set(obj) - set(allowed)):
        errors.append(f"{where}: unknown field '{key}'")
    missing = sorted(set(required) - set(obj))
    for key in missing:
        errors.append(f"{where}: missing field '{key}'")
    return not missing        # an object that lacks a required field is not looked at further


def validate_schema(schema: dict, config_fields: list[str] | None = None) -> None:
    """Raise SchemaError, listing every problem, unless the schema is complete and consistent. `config_fields` are the members of p6_config
    (by default read from bridge/include/p6.h): every one of them must be mapped by an option or be a fixed field of ABI v1."""
    errors: list[str] = []
    if not _only(schema, {"schema_version", "about", "categories", "options", "reserved", "unsupported"},
                 {"schema_version", "categories", "options", "reserved", "unsupported"}, "schema", errors):
        raise SchemaError("\n".join(errors))
    if schema.get("schema_version") != 1:
        errors.append("schema: schema_version must be 1")
    if "about" in schema and not (isinstance(schema["about"], list) and all(_text(line) for line in schema["about"])):
        errors.append("schema: about must be a list of ASCII lines")

    categories: set[str] = set()
    for i, category in enumerate(schema.get("categories") or []):
        where = f"categories[{i}]"
        if not _only(category, {"id", "label", "info"}, {"id", "label", "info"}, where, errors):
            continue
        if not (isinstance(category["id"], str) and IDENTIFIER.fullmatch(category["id"])):
            errors.append(f"{where}: id must be lowercase letters, digits and underscores")
        elif category["id"] in categories:
            errors.append(f"{where}: duplicate category '{category['id']}'")
        categories.add(str(category["id"]))
        for field in ("label", "info"):
            if not _text(category[field]):
                errors.append(f"{where}: {field} must be non-empty ASCII text")

    ids: set[str] = set()
    keys: set[str] = set()
    mapped: dict[str, str] = {}
    for i, option in enumerate(schema.get("options") or []):
        name = option.get("id") if isinstance(option, dict) else None
        where = f"option '{name}'" if isinstance(name, str) else f"options[{i}]"
        allowed = {"id", "class", "type", "maps_to", "default", "values", "min", "max", "libretro", "libretro_policy", "headless", "wrapper"}
        if not _only(option, allowed, {"id", "class", "type", "maps_to", "default", "libretro", "headless", "wrapper"}, where, errors):
            continue
        if not (isinstance(name, str) and IDENTIFIER.fullmatch(name)):
            errors.append(f"{where}: id must be lowercase letters, digits and underscores")
        elif name in ids:
            errors.append(f"{where}: duplicate option id")
        ids.add(str(name))
        kind, klass, maps_to = option["type"], option["class"], option["maps_to"]
        if klass not in ("reboot", "presentation"):
            errors.append(f"{where}: class must be 'reboot' or 'presentation', not {klass!r}")
        if kind not in ("enum", "u64", "i64"):
            errors.append(f"{where}: type must be 'enum', 'u64' or 'i64', not {kind!r}")
        if not (isinstance(maps_to, str) and re.fullmatch(r"(p6_config|presentation)\.[a-z][a-z0-9_]*", maps_to)):
            errors.append(f"{where}: maps_to must be 'p6_config.FIELD' or 'presentation.NAME'")
        else:
            target, _, field = maps_to.partition(".")
            if klass == "reboot" and target != "p6_config":
                errors.append(f"{where}: a reboot option must map to a p6_config field (it enters config_hash), not '{maps_to}'")
            if klass == "presentation" and (target != "presentation" or field != name):
                errors.append(f"{where}: a presentation option has no effect on emulation, so it maps to 'presentation.{name}', not '{maps_to}'")
            if target == "p6_config":
                if config_fields is not None and field not in config_fields:
                    errors.append(f"{where}: p6_config has no field '{field}'")
                if field in FIXED_CONFIG_FIELDS:
                    errors.append(f"{where}: p6_config.{field} has one valid value in ABI v1 and is not a choice")
            if maps_to in mapped:
                errors.append(f"{where}: maps_to '{maps_to}' is already used by option '{mapped[maps_to]}'")
            mapped[maps_to] = str(name)
        _validate_values(option, kind, where, errors)
        _validate_libretro(option, kind, where, categories, keys, errors)
        _validate_adapters(option, klass, where, errors)

    for i, entry in enumerate(schema.get("reserved") or []):
        where = f"reserved[{i}]"
        if _only(entry, {"id", "for", "wrapper_setting", "why"}, {"id", "for", "wrapper_setting", "why"}, where, errors):
            if not (isinstance(entry["id"], str) and IDENTIFIER.fullmatch(entry["id"])) or entry["id"] in ids:
                errors.append(f"{where}: id must be new lowercase letters, digits and underscores")
            ids.add(str(entry["id"]))
            for field in ("for", "wrapper_setting", "why"):
                if not _text(entry[field]):
                    errors.append(f"{where}: {field} must be non-empty ASCII text")
    seen_unsupported: set[str] = set()
    for i, entry in enumerate(schema.get("unsupported") or []):
        where = f"unsupported[{i}]"
        if _only(entry, {"key", "why"}, {"key", "why"}, where, errors):
            key = entry["key"]
            if not (isinstance(key, str) and IDENTIFIER.fullmatch(key)):
                errors.append(f"{where}: key must be lowercase letters, digits and underscores")
            elif key in seen_unsupported or key in ids:
                errors.append(f"{where}: '{key}' is already an option or listed as unsupported")
            seen_unsupported.add(str(key))
            if not _text(entry["why"]):
                errors.append(f"{where}: why must be non-empty ASCII text")

    if config_fields is not None:
        for field in config_fields:
            if field not in FIXED_CONFIG_FIELDS and f"p6_config.{field}" not in mapped:
                errors.append(f"p6_config.{field} is not covered: map an option to it or declare it fixed in tools/generate_options.py")
    if errors:
        raise SchemaError("\n".join(errors))


def _validate_values(option, kind, where, errors):
    if kind == "enum":
        values = option.get("values")
        if "min" in option or "max" in option:
            errors.append(f"{where}: an enum has no min/max")
        if not (isinstance(values, list) and values):
            errors.append(f"{where}: an enum needs a non-empty values list")
            return
        names, abis = set(), set()
        for j, value in enumerate(values):
            if not _only(value, {"value", "abi", "abi_name", "label", "wrapper"}, {"value", "abi", "label"}, f"{where} values[{j}]", errors):
                continue
            if "wrapper" in value and (value["wrapper"] is not False or not (isinstance(option.get("wrapper"), dict) and option["wrapper"].get("how") == "setting")):
                errors.append(f"{where} values[{j}]: wrapper may only be false (the BizHawk wrapper does not offer this value), on an option the wrapper takes as a setting")
            if not _text(value["value"]) or not _text(value["label"]):
                errors.append(f"{where} values[{j}]: value and label must be non-empty ASCII text")
            if value["value"] in names:
                errors.append(f"{where}: duplicate value '{value['value']}'")
            names.add(value["value"])
            abi = value["abi"]
            if not (isinstance(abi, int) and not isinstance(abi, bool) and 0 <= abi < 2**32):
                errors.append(f"{where} values[{j}]: abi must be an integer of 32 bits")
            elif abi in abis:
                errors.append(f"{where}: duplicate abi value {abi}")
            abis.add(abi)
            if "abi_name" in value and not (isinstance(value["abi_name"], str) and re.fullmatch(r"P6_[A-Z0-9_]+", value["abi_name"])):
                errors.append(f"{where} values[{j}]: abi_name must be a P6_ constant name")
        if option["default"] not in names:
            errors.append(f"{where}: default {option['default']!r} is not one of the values {sorted(names)}")
    elif kind in INT_TYPES:
        _, lowest, highest = INT_TYPES[kind]
        if "values" in option:
            errors.append(f"{where}: a number has min/max, not a values list")
        low, high, default = option.get("min"), option.get("max"), option["default"]
        ints = all(isinstance(x, int) and not isinstance(x, bool) for x in (low, high, default))
        if not ints:
            errors.append(f"{where}: min, max and default must be integers")
        elif not (lowest <= low <= default <= high <= highest):
            errors.append(f"{where}: default {default} is not within min {low} and max {high} ({kind})")


def _validate_libretro(option, kind, where, categories, keys, errors):
    libretro = option["libretro"]
    if libretro is None:
        if not _text(option.get("libretro_policy"), 20):
            errors.append(f"{where}: a key that libretro does not offer needs a libretro_policy that says why")
        return
    if "libretro_policy" in option:
        errors.append(f"{where}: libretro_policy is only for a key libretro does not offer")
    if kind != "enum":
        errors.append(f"{where}: libretro offers enums only (a number would need a free-form field the frontends do not have)")
    if not _only(libretro, {"key", "category", "label", "info"}, {"key", "category", "label", "info"}, f"{where} libretro", errors):
        return
    key = libretro["key"]
    if not (isinstance(key, str) and LIBRETRO_KEY.fullmatch(key)):
        errors.append(f"{where}: libretro key must be 'puae6_' and lowercase letters, digits and underscores")
    elif key in keys:
        errors.append(f"{where}: duplicate libretro key '{key}'")
    keys.add(str(key))
    if libretro["category"] not in categories:
        errors.append(f"{where}: libretro category '{libretro['category']}' is not declared")
    for field in ("label", "info"):
        if not _text(libretro[field]):
            errors.append(f"{where}: libretro {field} must be non-empty ASCII text")
    if isinstance(option.get("values"), list) and len(option["values"]) > MAX_VALUES:
        errors.append(f"{where}: libretro takes at most {MAX_VALUES} values")


def _validate_adapters(option, klass, where, errors):
    headless, wrapper = option["headless"], option["wrapper"]
    if _only(headless, {"how", "flag", "sets", "names"}, {"how"}, f"{where} headless", errors):
        how = headless["how"]
        if how not in ("flag", "value", "choice", "fixed", "none"):
            errors.append(f"{where}: headless how must be flag, value, choice, fixed or none")
        needed = {"flag": {"flag", "sets"}, "value": {"flag"}, "choice": {"flag", "names"}}.get(how, set())
        if set(headless) - {"how"} != needed:
            errors.append(f"{where}: headless '{how}' takes exactly the fields {sorted(needed)}")
        if how == "flag" and option["type"] == "enum" and headless.get("sets") not in [v.get("value") for v in option.get("values", [])]:
            errors.append(f"{where}: headless flag sets {headless.get('sets')!r}, which is not a value")
        if how == "choice" and "names" in headless:
            names = headless["names"]
            values = [v.get("value") for v in option.get("values", [])] if option["type"] == "enum" else []
            if not (isinstance(names, dict) and sorted(names) == sorted(values) and all(_text(spelling) and spelling == spelling.lower() for spelling in names.values())
                    and len(set(names.values())) == len(names)):
                errors.append(f"{where}: headless 'choice' names every value of an enum once, in lowercase ASCII (the spelling after the flag)")
        if (how == "none") != (klass == "presentation"):
            errors.append(f"{where}: headless 'none' is for presentation options only (a reboot option is part of the machine headless runs)")
    if _only(wrapper, {"how", "setting", "type", "where"}, {"how"}, f"{where} wrapper", errors):
        how = wrapper["how"]
        if how not in ("setting", "fixed", "none"):
            errors.append(f"{where}: wrapper how must be setting, fixed or none")
        needed = {"setting": {"setting", "type"}, "fixed": {"where"}}.get(how, set())
        if set(wrapper) - {"how"} != needed:
            errors.append(f"{where}: wrapper '{how}' takes exactly the fields {sorted(needed)}")
        if (how == "none") != (klass == "presentation"):
            errors.append(f"{where}: wrapper 'none' is for presentation options only")


# --- normalization: one requested configuration against the schema ---------------------------------------------------------------------

def _option_index(schema: dict) -> dict:
    return {option["id"]: option for option in schema["options"]}


def normalize_value(option: dict, raw) -> object:
    """The normalized value of `raw` for `option`: the value name for an enum, an integer for a number. ConfigError otherwise."""
    name = option["id"]
    if option["type"] == "enum":
        names = [value["value"] for value in option["values"]]
        if not isinstance(raw, str) or raw not in names:
            raise ConfigError(f"option {name}: the value {raw!r} is not supported (allowed: {', '.join(names)})")
        return raw
    # At most 64 digits: int() refuses a longer text with a bare ValueError (a limit that depends on the Python version) that does not name the option.
    if isinstance(raw, str) and re.fullmatch(r"-?[0-9]{1,64}", raw):
        raw = int(raw)
    if not isinstance(raw, int) or isinstance(raw, bool) or not option["min"] <= raw <= option["max"]:
        raise ConfigError(f"option {name}: the value {raw!r} is not an integer from {option['min']} to {option['max']}")
    return raw


def normalize_config(schema: dict, requested: dict) -> dict:
    """Every option with a value: the requested one, normalized, or the schema's default. A key that is not in the schema is refused with the
    reason when it is a known-unsupported one (CPU, RAM, ROM, other machines) and as unknown otherwise; nothing is half-accepted."""
    if not isinstance(requested, dict):
        raise ConfigError(f"the requested configuration must be a mapping of option names to values, not {type(requested).__name__}")
    options = _option_index(schema)
    unsupported = {entry["key"]: entry["why"] for entry in schema["unsupported"]}
    reserved = {entry["id"]: entry for entry in schema["reserved"]}
    problems = []
    for key in requested:
        if key in options:
            continue
        if key in unsupported:
            problems.append(f"option {key} is not supported: {unsupported[key]}")
        elif key in reserved:
            problems.append(f"option {key} is not available yet: {reserved[key]['why']}")
        else:
            problems.append(f"option {key} is unknown (supported: {', '.join(options)})")
    result = {}
    for name, option in options.items():
        try:
            result[name] = normalize_value(option, requested[name]) if name in requested else option["default"]
        except ConfigError as error:
            problems.append(str(error))
    if problems:
        raise ConfigError("\n".join(problems))
    return result


def abi_value(option: dict, normalized) -> int:
    """The number that goes into the p6_config field (or, for presentation, into Settings) for a normalized value."""
    if option["type"] == "enum":
        return next(value["abi"] for value in option["values"] if value["value"] == normalized)
    return normalized


def to_p6_config(schema: dict, normalized: dict) -> dict:
    """The p6_config fields (name -> number) that a normalized configuration produces."""
    return {option["maps_to"].partition(".")[2]: abi_value(option, normalized[option["id"]])
            for option in schema["options"] if option["maps_to"].startswith("p6_config.")}


# --- generated header ------------------------------------------------------------------------------------------------------------------

def _c(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _camel(identifier: str) -> str:
    return "".join(part.capitalize() for part in identifier.split("_"))


def _field_type(option: dict) -> str:
    return "uint32_t" if option["type"] == "enum" else INT_TYPES[option["type"]][0]


def _literal(option: dict, value: int) -> str:
    return {"enum": f"{value}u", "u64": f"UINT64_C({value})", "i64": f"INT64_C({value})"}[option["type"]]


def _description(option: dict) -> tuple[str, str]:
    """The label and the help text a frontend shows; a reboot option says so in both."""
    libretro = option["libretro"]
    reboot = option["class"] == "reboot"
    return libretro["label"] + (REBOOT_SUFFIX if reboot else ""), libretro["info"] + (REBOOT_SENTENCE if reboot else "")


def generate_header(schema: dict) -> str:
    options = schema["options"]
    exposed = [option for option in options if option["libretro"]]
    out: list[str] = []
    w = out.append
    w(f"// {PREAMBLE}")
    w("#ifndef P6_LIBRETRO_OPTIONS_GENERATED_H")
    w("#define P6_LIBRETRO_OPTIONS_GENERATED_H")
    w("")
    w('#include "libretro.h"')
    w('#include "p6.h"')
    w("")
    w("#include <stdint.h>")
    w("")
    w("namespace p6_options {")
    w("")
    w("// Every key of the schema with its default. The reboot keys are p6_config fields (to_config); the presentation keys never reach the")
    w("// machine. A key libretro does not offer keeps its default here, which is the only value the core ever uses for it.")
    w("struct Settings {")
    for option in options:
        default = abi_value(option, option["default"])
        note = f"  // {option['class']}, {option['maps_to']}" + (f" = {option['default']}" if option["type"] == "enum" else "")
        w(f"    {_field_type(option)} {option['id']} = {_literal(option, default)};{note}")
    w("};")
    w("")
    w("inline void to_config(const Settings &settings, p6_config *config)")
    w("{")
    for option in options:
        if option["class"] == "reboot":
            w(f"    config->{option['maps_to'].partition('.')[2]} = settings.{option['id']};")
    w("}")
    w("")
    w("// The options libretro offers: the value names the frontend stores and the number each stands for in Settings.")
    w("struct Value {")
    w("    const char *name;")
    w("    uint32_t number;")
    w("};")
    w("")
    w("struct Option {")
    w("    const char *key;")
    w("    bool reboot;                        // part of the machine: a change needs a reload and is never applied to the running one")
    w("    uint32_t Settings::*field;")
    w("    const Value *values;")
    w("    unsigned count;")
    w("    unsigned default_index;")
    w("};")
    w("")
    for option in exposed:
        w(f"constexpr Value k{_camel(option['id'])}Values[] = {{")
        for value in option["values"]:
            w(f"    {{{_c(value['value'])}, {value['abi']}u}},")
        w("};")
    w("")
    w("constexpr Option kOptions[] = {")
    for option in exposed:
        index = [v["value"] for v in option["values"]].index(option["default"])
        values = f"k{_camel(option['id'])}Values"
        w(f"    {{{_c(option['libretro']['key'])}, {'true' if option['class'] == 'reboot' else 'false'}, &Settings::{option['id']}, {values}, "
          f"{len(option['values'])}, {index}}},")
    w("};")
    w("constexpr unsigned kOptionCount = sizeof kOptions / sizeof kOptions[0];")
    w("")
    w("// retro_core_option_v2: categories and definitions, each array ends with an empty element.")
    w("// Not const: libretro's structs take non-const pointers. The frontend only reads them.")
    w("inline retro_core_option_v2_category kCategoriesV2[] = {")
    for category in schema["categories"]:
        w(f"    {{{_c(category['id'])}, {_c(category['label'])}, {_c(category['info'])}}},")
    w("    {nullptr, nullptr, nullptr},")
    w("};")
    w("")
    w("inline retro_core_option_v2_definition kDefinitionsV2[] = {")
    for option in exposed:
        desc, info = _description(option)
        values = ", ".join(f"{{{_c(v['value'])}, {_c(v['label'])}}}" for v in option["values"])
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc)}, {_c(desc)},")
        w(f"     {_c(info)},")
        w(f"     {_c(info)},")
        w(f"     {_c(option['libretro']['category'])}, {{{values}}}, {_c(option['default'])}}},")
    w("    {nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, {}, nullptr},")
    w("};")
    w("inline retro_core_options_v2 kOptionsV2 = {kCategoriesV2, kDefinitionsV2};")
    w("")
    w("// retro_core_option (version 1): no categories.")
    w("constexpr retro_core_option_definition kDefinitionsV1[] = {")
    for option in exposed:
        desc, info = _description(option)
        values = ", ".join(f"{{{_c(v['value'])}, {_c(v['label'])}}}" for v in option["values"])
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc)}, {_c(info)}, {{{values}}}, {_c(option['default'])}}},")
    w("    {nullptr, nullptr, nullptr, {}, nullptr},")
    w("};")
    w("")
    w("// Legacy SET_VARIABLES: \"Description; default|other|...\" (the default comes first).")
    w("constexpr retro_variable kVariables[] = {")
    for option in exposed:
        desc, _ = _description(option)
        names = [v["value"] for v in option["values"]]
        names.remove(option["default"])
        w(f"    {{{_c(option['libretro']['key'])}, {_c(desc + '; ' + '|'.join([option['default']] + names))}}},")
    w("    {nullptr, nullptr},")
    w("};")
    w("")
    w("}  // namespace p6_options")
    w("")
    w("#endif")
    return "\n".join(out) + "\n"


def generate_table(schema: dict) -> str:
    """The table adapters must respect: the p6_config fields as numbers, and how each adapter takes its value."""
    config, presentation, adapters = {}, {}, {}
    for option in schema["options"]:
        if option["type"] == "enum":
            allowed = [value["abi"] for value in option["values"]]
            entry = {"default": abi_value(option, option["default"]), "allowed": allowed,
                     "names": {value["value"]: value["abi"] for value in option["values"]}}
        else:
            entry = {"default": option["default"], "min": option["min"], "max": option["max"]}
        entry["option"] = option["id"]
        entry["class"] = option["class"]
        (config if option["class"] == "reboot" else presentation)[option["maps_to"].partition(".")[2]] = entry
        adapters[option["id"]] = {"headless": option["headless"], "wrapper": option["wrapper"],
                                  "libretro": option["libretro"]["key"] if option["libretro"] else None}
        withheld = [value["value"] for value in option.get("values", []) if value.get("wrapper") is False]
        if withheld:
            adapters[option["id"]]["wrapper_not_offered"] = withheld
    document = {"generated_by": PREAMBLE, "p6_config": config, "presentation": presentation, "adapters": adapters,
                "reserved": {entry["id"]: entry["wrapper_setting"] for entry in schema["reserved"]},
                "unsupported": {entry["key"]: entry["why"] for entry in schema["unsupported"]}}
    return json.dumps(document, indent=2, sort_keys=False) + "\n"


def outputs(schema: dict) -> dict[Path, str]:
    return {HEADER: generate_header(schema), TABLE: generate_table(schema)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file differs from what the schema produces")
    parser.add_argument("--schema", type=Path, default=SCHEMA)
    parser.add_argument("--header", type=Path, default=HEADER)
    parser.add_argument("--table", type=Path, default=TABLE)
    args = parser.parse_args(argv)
    try:
        schema = load_schema(args.schema)
        validate_schema(schema, p6_config_fields())
    except (SchemaError, OSError, json.JSONDecodeError) as error:
        print(f"{args.schema}: {error}", file=sys.stderr)
        return 1
    generated = {args.header: generate_header(schema), args.table: generate_table(schema)}
    status = 0
    for path, text in generated.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                print(f"{path}: {'missing' if current is None else 'stale'}; run python3 tools/generate_options.py", file=sys.stderr)
                status = 1
        elif current != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    return status


if __name__ == "__main__":
    sys.exit(main())
