#!/usr/bin/env python3
"""Derive only our P6Assign and recipe data; never embed user WHDLoad or ROMs."""
import argparse
import json
from pathlib import Path
from whdload import bundle

ROOT = Path(__file__).resolve().parents[1]


def products():
    config = json.loads((ROOT / "config/whdload/fatal-mission.json").read_text())
    program = next(f["sha256"] for f in config["files"] if f["to"] == "C/WHDLoad")
    strings = dict(ProgramSha256=program, VfsSha256=bundle.VFS_SHA256, StartupSequence=bundle.STARTUP_SEQUENCE.decode(),
                   Preferences=bundle.PREFERENCES.decode(), ButtonWaitLine=bundle.BUTTON_WAIT_LINE.decode())
    arrays = dict(Names=bundle.NAMES, Labels=bundle.LABELS, FreeBlocks=bundle.FREE_BLOCKS)
    numbers = dict(ZipMadeBy=bundle.ZIP_MADE_BY, ZipExternalAttributes=bundle.ZIP_EXTERNAL_ATTRIBUTES, ZipDosDate=bundle.ZIP_DOS_DATE)
    comment = "// Generated by tools/generate_whdload.py from T65a; no user binaries."
    cpp = [comment, "#pragma once", "#include <stdint.h>", "namespace p6_libretro { namespace whdload_data {"]
    cs = [comment, "namespace Puae6;", "internal static class WhdLoadData", "{"]
    for name, value in strings.items():
        cpp.append(f"inline constexpr char k{name}[] = {json.dumps(value)};")
        cs.append(f"    internal const string {name} = {json.dumps(value)};")
    for name, values in arrays.items():
        kind = "int" if name == "FreeBlocks" else "string"
        encoded = ", ".join(map(str, values)) if kind == "int" else ", ".join(map(json.dumps, values))
        cpp.append(f"inline constexpr {'uint32_t' if kind == 'int' else 'const char *'} k{name}[] = {{{encoded}}};")
        cs.append(f"    internal static readonly {kind}[] {name} = {{{encoded}}};")
    for name, value in numbers.items():
        cpp.append(f"inline constexpr uint32_t k{name} = {value};")
        cs.append(f"    internal const uint {name} = {value};")
    encoded = ",".join("0x%02x" % b for b in bundle.assign_program())
    cpp += ["inline constexpr uint8_t kAssignProgram[] = {" + encoded + "};", "}}", ""]
    cs += ["    internal static readonly byte[] AssignProgram = {" + encoded + "};", "}", ""]
    return {"adapters/libretro/whdload_data.generated.h": "\n".join(cpp),
            "integration/bizhawk/core/Puae6/WHDLoadData.generated.cs": "\n".join(cs)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in products().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text() != data:
                parser.exit(1, "stale WHDLoad generated data: " + name + "\n")
        else:
            path.write_text(data)


if __name__ == "__main__":
    main()
