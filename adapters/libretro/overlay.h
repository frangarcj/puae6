constexpr int kGlyphWidth = 5, kGlyphHeight = 7, kGlyphAdvance = 6;       // columns and rows of a glyph, and the distance to the next one

// A picture to draw on: XRGB8888 pixels, `stride` pixels from one row to the next.
struct Canvas {
    uint32_t *pixels = nullptr;
    uint32_t width = 0, height = 0;
    size_t stride = 0;
};

