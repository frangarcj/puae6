// The glyph rows of a character: capitals for lower case, the arrows for '~' (down), '{' (left) and '}' (right), the grave accent, nullptr for anything else.
inline const uint8_t *glyph(char c)
{
    static const uint8_t down[kGlyphHeight] = {0x04, 0x04, 0x04, 0x04, 0x15, 0x0E, 0x04};
    static const uint8_t left[kGlyphHeight] = {0x00, 0x04, 0x08, 0x1F, 0x08, 0x04, 0x00};
    static const uint8_t right[kGlyphHeight] = {0x00, 0x04, 0x02, 0x1F, 0x02, 0x04, 0x00};
    if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');
    if (c >= ' ' && c <= '_') return kFont[c - ' '];
    static const uint8_t grave[kGlyphHeight] = {0x08, 0x04, 0x02, 0x00, 0x00, 0x00, 0x00};
    if (c == '`') return grave;
    if (c == '~') return down;
    if (c == '{') return left;
    if (c == '}') return right;
    return nullptr;
}

inline uint32_t blend(uint32_t below, uint32_t above, unsigned alpha)       // alpha 0..255 of `above` over `below`
{
    if (alpha >= 255) return above & 0x00FFFFFFu;
    if (alpha == 0) return below & 0x00FFFFFFu;
    const unsigned inverse = 255 - alpha;
    const unsigned r = (((below >> 16) & 255) * inverse + ((above >> 16) & 255) * alpha + 127) / 255;
    const unsigned g = (((below >> 8) & 255) * inverse + ((above >> 8) & 255) * alpha + 127) / 255;
    const unsigned b = ((below & 255) * inverse + (above & 255) * alpha + 127) / 255;
    return r << 16 | g << 8 | b;
}

// A rectangle of `color` with `alpha` (255: opaque), clipped to the canvas.
inline void fill_rect(const Canvas &canvas, int x, int y, int width, int height, uint32_t color, unsigned alpha = 255)
{
    const int x0 = std::max(0, x), y0 = std::max(0, y);
    const int x1 = std::min<int>(int(canvas.width), x + width), y1 = std::min<int>(int(canvas.height), y + height);
    for (int j = y0; j < y1; ++j) {
        uint32_t *row = canvas.pixels + size_t(j) * canvas.stride;
        for (int i = x0; i < x1; ++i) row[i] = blend(row[i], color, alpha);
    }
}

inline void put_pixel(const Canvas &canvas, int x, int y, uint32_t color)
{
    if (x >= 0 && y >= 0 && x < int(canvas.width) && y < int(canvas.height)) canvas.pixels[size_t(y) * canvas.stride + size_t(x)] = color & 0x00FFFFFFu;
}

// The width of a text in pixels at `scale`.
inline int text_width(const char *text, int scale) { return text && *text ? int(strlen(text)) * kGlyphAdvance * scale - scale : 0; }

enum class TextStyle { Plain, Shadow, Outline };

// A text with its top-left at (x, y); each glyph pixel is a scale x scale square. A Shadow is a copy one pixel (scale) down and right, an Outline a copy
// in each of the eight directions, both in `edge`. A character the font does not have is a box.
inline void draw_text(const Canvas &canvas, int x, int y, const char *text, int scale, uint32_t color, TextStyle style = TextStyle::Plain, uint32_t edge = 0)
{
    auto draw = [&](int ox, int oy, uint32_t paint) {
        for (int pen = x; text && *text; ++text, pen += kGlyphAdvance * scale) {
            const uint8_t *rows = glyph(*text);
            for (int j = 0; j < kGlyphHeight; ++j)
                for (int i = 0; i < kGlyphWidth; ++i) {
                    const bool set = rows ? (rows[j] >> (kGlyphWidth - 1 - i) & 1) : (i == 0 || i == kGlyphWidth - 1 || j == 0 || j == kGlyphHeight - 1);
                    if (set) fill_rect(canvas, pen + ox + i * scale, y + oy + j * scale, scale, scale, paint);
                }
        }
    };
    const char *begin = text;
    if (style == TextStyle::Shadow) {
        draw(scale, scale, edge);
    } else if (style == TextStyle::Outline) {
        for (int dy = -1; dy <= 1; ++dy)
            for (int dx = -1; dx <= 1; ++dx)
                if (dx || dy) {
                    text = begin;
                    draw(dx * scale, dy * scale, edge);
                }
    }
    text = begin;
    draw(0, 0, color);
}

