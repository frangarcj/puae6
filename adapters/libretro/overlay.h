// Drawing on the picture the frontend gets (T31b, T31a): a 5x7 pixel font and the few operations the statusbar and the virtual keyboard need (rectangles with
// transparency, text with a shadow or an outline). Everything draws on a COPY of the picture that present.h made (a Canvas of 32-bit XRGB pixels); the picture the
// engine drew, the machine and the state never see a pixel of it. The font is this project's own: 96 glyphs of 5 columns and 7 rows (capital letters, digits,
// punctuation, four arrows), lower case drawn as capitals; a code the font does not have is drawn as a box.
